        $originalAcl = Get-Acl -LiteralPath $softwareHiveFull
        Set-Acl -LiteralPath $newHive -AclObject $originalAcl
        [IO.File]::SetAttributes($newHive, (Get-Item -LiteralPath $softwareHiveFull -Force).Attributes)
        [IO.File]::Replace($newHive, $softwareHiveFull, $backupHive, $true)
        if ((Get-FileHash -LiteralPath $softwareHiveFull -Algorithm SHA256).Hash -ne $newHash) {
            throw 'Atomic offline SOFTWARE hive replacement did not retain the verified automatic-logon policy.'
        }
        Remove-Item -LiteralPath $backupHive -Force -ErrorAction Stop
        return [pscustomobject]@{
            AutoAdminLogon = $true
            ForceAutoLogon = $true
            DefaultUserName = $UserName
            DefaultDomainName = $ComputerName
            AutoLogonCountAbsent = $true
            PlaintextDefaultPasswordAbsent = $true
            DisableCad = $true
            InteractiveLegalNoticeAbsent = $true
        }
    }
    catch {
        $primaryFailure = $_.Exception
        if (Test-Path -LiteralPath $backupHive -PathType Leaf) {
            try { [IO.File]::Replace($backupHive, $softwareHiveFull, $null, $true) }
            catch {
                $rollbackFailed = $true
                throw "Offline SOFTWARE hive update failed and its atomic rollback also failed. Original error: $($primaryFailure.Message). Rollback error: $($_.Exception.Message)"
            }
        }
        throw $primaryFailure
    }
    finally {
        if (Test-Path -LiteralPath $newHive -PathType Leaf) { Remove-Item -LiteralPath $newHive -Force -ErrorAction SilentlyContinue }
        if (-not $rollbackFailed -and (Test-Path -LiteralPath $backupHive -PathType Leaf)) { Remove-Item -LiteralPath $backupHive -Force -ErrorAction SilentlyContinue }
    }
}


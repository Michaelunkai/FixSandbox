    for ($attempt = 1; $attempt -le 10; $attempt++) {
        try {
            $encodedParts = @(Invoke-Command -VMName $Name -Credential $Credential -ArgumentList $FileName, $MaximumBytes -ScriptBlock {
                param([string]$RequestedFile, [int]$MaximumLength)
                $root = [IO.Path]::GetFullPath('C:\ProgramData\CodexReplicaValidation\')
                $path = [IO.Path]::GetFullPath((Join-Path $root $RequestedFile))
                if (-not $path.StartsWith($root, [StringComparison]::OrdinalIgnoreCase)) { throw 'PowerShell Direct artifact path escaped its fixed root.' }
                if (-not (Test-Path -LiteralPath $path -PathType Leaf)) { throw "Runtime artifact is missing: $RequestedFile" }
                if ($RequestedFile -eq 'evidence.json') {
                    $launcher = 'C:\ProgramData\Microsoft\Windows\Start Menu\Programs\StartUp\CodexReplicaVerify.cmd'
                    if (Test-Path -LiteralPath $launcher) { throw 'The successful verifier did not remove its persistent startup launcher.' }
                    $bitLocker = Get-BitLockerVolume -MountPoint 'C:' -ErrorAction Stop
                    if ([string]$bitLocker.VolumeStatus -ne 'FullyDecrypted' -or [string]$bitLocker.ProtectionStatus -ne 'Off' -or [int]$bitLocker.EncryptionPercentage -ne 0) {
                        throw 'The live guest system volume is no longer fully decrypted with protection off.'
                    }
                    $preventDeviceEncryption = [int](Get-ItemProperty -LiteralPath 'HKLM:\SYSTEM\CurrentControlSet\Control\BitLocker' -Name PreventDeviceEncryption -ErrorAction Stop).PreventDeviceEncryption
                    if ($preventDeviceEncryption -ne 1) { throw 'The live guest no longer blocks automatic device encryption.' }
                    $winlogon = Get-ItemProperty -LiteralPath 'HKLM:\SOFTWARE\Microsoft\Windows NT\CurrentVersion\Winlogon' -ErrorAction Stop
                    $systemPolicy = Get-ItemProperty -LiteralPath 'HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Policies\System' -ErrorAction Stop
                    if (
                        [string]$winlogon.AutoAdminLogon -ne '1' -or
                        [string]$winlogon.DefaultUserName -ne [Environment]::UserName -or
                        [string]$winlogon.DefaultDomainName -ne [Environment]::MachineName -or
                        [string]$winlogon.ForceAutoLogon -ne '1' -or
                        [int]$winlogon.DisableCAD -ne 1 -or
                        $null -ne $winlogon.PSObject.Properties['AutoLogonCount'] -or
                        $null -ne $winlogon.PSObject.Properties['DefaultPassword'] -or
                        -not [string]::IsNullOrEmpty([string]$systemPolicy.legalnoticecaption) -or
                        -not [string]::IsNullOrEmpty([string]$systemPolicy.legalnoticetext)
                    ) {
                        throw 'The live guest no longer has persistent password-prompt-free automatic logon.'
                    }
                    $rdvService = Get-Service -Name 'vmicrdv' -ErrorAction Stop
                    if ([string]$rdvService.StartType -ne 'Disabled' -or [string]$rdvService.Status -ne 'Stopped') {
                        throw 'The live guest still permits Hyper-V Enhanced Session Mode and its separate RDP credential prompt.'
                    }
                }
                $item = Get-Item -LiteralPath $path -ErrorAction Stop
                if ($item.Length -le 0 -or $item.Length -gt $MaximumLength) { throw "Runtime artifact has an invalid length: $RequestedFile" }
                [Convert]::ToBase64String([IO.File]::ReadAllBytes($path))
            } -ErrorAction Stop)
            $encoded = (@($encodedParts) | ForEach-Object { [string]$_ }) -join ''
            if ([string]::IsNullOrWhiteSpace($encoded)) { throw 'PowerShell Direct returned an empty artifact.' }
            $bytes = [Convert]::FromBase64String($encoded)
            if ($bytes.Length -le 0 -or $bytes.Length -gt $MaximumBytes) { throw 'PowerShell Direct returned an invalid artifact length.' }
            return [Text.Encoding]::UTF8.GetString($bytes)
        }
        catch {
            $lastFailure = $_.Exception.Message
            if ($attempt -lt 10) { Start-Sleep -Seconds 2 }
        }
    }
    throw "Credential-authenticated PowerShell Direct could not retrieve $FileName from $Name after 10 attempts: $lastFailure"
}

function Get-CodexGuestEvidenceViaPowerShellDirect {
    param(
        [string]$Name,
        [System.Management.Automation.PSCredential]$Credential
    )

    $json = Get-CodexGuestFileViaPowerShellDirect -Name $Name -Credential $Credential -FileName 'evidence.json'
    try { $evidence = $json | ConvertFrom-Json }
    catch { throw "PowerShell Direct runtime evidence is not valid JSON: $($_.Exception.Message)" }
    $sha256 = [Security.Cryptography.SHA256]::Create()
    try {
        $evidenceHash = ([BitConverter]::ToString($sha256.ComputeHash([Text.Encoding]::UTF8.GetBytes($json)))).Replace('-', '')
    }
    finally { $sha256.Dispose() }
    $evidence | Add-Member -MemberType NoteProperty -Name EvidenceSha256 -Value $evidenceHash -Force
    $evidence | Add-Member -MemberType NoteProperty -Name PowerShellDirectAuthenticated -Value $true -Force
    $evidence | Add-Member -MemberType NoteProperty -Name VerifierLauncherAbsent -Value $true -Force
    return $evidence
}


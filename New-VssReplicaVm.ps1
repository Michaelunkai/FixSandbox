#requires -RunAsAdministrator

<#
.SYNOPSIS
    Captures, builds, validates, and launches the closest practical Hyper-V
    replica of the current Windows machine and its fixed data volumes.

.DESCRIPTION
    This is the repeatable VSS/P2V entrypoint. It asks Windows Backup for an
    application-consistent image of C: plus every critical boot volume. It also
    recreates every other fixed disk with the original disk signature,
    partition offsets, filesystem, allocation unit, labels, drive-letter
    mappings, and a verified mirror of its data. It makes self-contained VHDX
    base copies, creates disposable differencing disks, installs a
    partition-independent UEFI BCD store, builds a Generation 2 VM, and starts
    it only after all offline fidelity gates pass.

    The Windows volume is used block-for-block from the VSS backup. It is not
    reconstructed with a file copy, so reparse points, ACLs, alternate streams,
    installed applications, registry hives, profiles, and shortcuts in C: are
    preserved by the backup image itself.

    NTFS data volumes are normally read through VSS snapshots. When a source
    disk also stores its replica, the script instead performs repeated live
    passes until Robocopy reports no differences; this avoids stressing a VSS
    snapshot with a large destination on the same physical disk. Filesystems
    without VSS support use the same convergence rule. Storage Optimizer and
    ScheduledDefrag are guarded during construction and restored before launch.
    Generated backup/replica artifacts are excluded from a same-disk data copy
    to avoid impossible recursive self-inclusion, and are recorded explicitly
    in the manifest.
#>

[CmdletBinding()]
param(
    [ValidatePattern('^[A-Za-z]:$')]
    [string]$BackupTarget = 'F:',

    [string]$ReplicaRoot,

    [string]$VMName,

    [ValidateRange(4, 64)]
    [int]$StartupMemoryGB = 16,

    [ValidateRange(1, 32)]
    [int]$ProcessorCount = 4,

    [ValidateRange(60, 900)]
    [int]$BootTimeoutSeconds = 300,

    [ValidateSet('Isolated', 'DefaultSwitch')]
    [string]$NetworkMode = 'Isolated',

    [switch]$ReuseLatestBackup,

    [switch]$NoLaunch,

    [switch]$SkipFixedDataVolumes,

    [switch]$PreflightOnly,

    [ValidateRange(2, 20)]
    [int]$DataSyncPasses = 8,

    [switch]$CodexDesktopReplica,

    [ValidatePattern('^$|^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$')]
    [string]$ExpectedCodexSessionId = '',

    [ValidateLength(0, 200)]
    [string]$ExpectedCodexTaskTitle = '',

    [ValidateRange(180, 1200)]
    [int]$CodexValidationTimeoutSeconds = 600,

    [switch]$ResumeIncomplete,

    [switch]$ReplaceIncompleteReplica,

    [switch]$EnsureExistingAutoLogon,

    [switch]$KeepConsoleClosed,

    [switch]$StopExistingReplica,

    [switch]$InspectExistingReplicaOffline,

    [switch]$DisableHostEnhancedSessionOnly,

    [ValidatePattern('^$|^[A-Za-z]:\\.+\.vhdx$')]
    [string]$BackupTargetVhdPath = '',

    [ValidatePattern('^[A-Za-z]:$')]
    [string]$BackupTargetVhdDrive = 'R:',

    [ValidateRange(256, 1024)]
    [int]$BackupTargetVhdSizeGB = 512,

    [ValidatePattern('^$|^[A-Za-z]:\\WindowsImageBackup\\?$')]
    [string]$RemoveFailedBackupRoot = ''
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

# PowerShell 7 can pass a module-search environment into Windows PowerShell
# that prevents normal discovery of this inbox module. Resolve it explicitly so
# the one script has the same hashing/JSON primitives regardless of its parent.
if ($null -eq (Get-Command Get-FileHash -ErrorAction SilentlyContinue)) {
    $utilityModuleManifest = Join-Path $env:SystemRoot 'System32\WindowsPowerShell\v1.0\Modules\Microsoft.PowerShell.Utility\Microsoft.PowerShell.Utility.psd1'
    Import-Module -Name $utilityModuleManifest -Force -ErrorAction Stop
}

if ($KeepConsoleClosed -and -not $EnsureExistingAutoLogon) {
    throw '-KeepConsoleClosed is valid only with -EnsureExistingAutoLogon.'
}

if ($StopExistingReplica) {
    if ([string]::IsNullOrWhiteSpace($VMName)) { throw '-StopExistingReplica requires the exact -VMName.' }
    if ($EnsureExistingAutoLogon -or $KeepConsoleClosed -or $PreflightOnly -or $NoLaunch -or $ResumeIncomplete -or $ReplaceIncompleteReplica -or $ReuseLatestBackup) {
        throw '-StopExistingReplica is an isolated close-and-shutdown mode and cannot be combined with another workflow mode.'
    }
}

if ($InspectExistingReplicaOffline) {
    if ([string]::IsNullOrWhiteSpace($VMName)) { throw '-InspectExistingReplicaOffline requires the exact -VMName.' }
    if ($EnsureExistingAutoLogon -or $KeepConsoleClosed -or $StopExistingReplica -or $PreflightOnly -or $NoLaunch -or $ResumeIncomplete -or $ReplaceIncompleteReplica -or $ReuseLatestBackup) {
        throw '-InspectExistingReplicaOffline is an isolated read-only diagnostic mode and cannot be combined with another workflow mode.'
    }
}

if ($DisableHostEnhancedSessionOnly) {
    if ([string]::IsNullOrWhiteSpace($VMName)) { throw '-DisableHostEnhancedSessionOnly requires the exact -VMName.' }
    if ($EnsureExistingAutoLogon -or $KeepConsoleClosed -or $StopExistingReplica -or $InspectExistingReplicaOffline -or $PreflightOnly -or $NoLaunch -or $ResumeIncomplete -or $ReplaceIncompleteReplica -or $ReuseLatestBackup) {
        throw '-DisableHostEnhancedSessionOnly is an isolated offline host-policy mode and cannot be combined with another workflow mode.'
    }
}

if ($EnsureExistingAutoLogon) {
    if ([string]::IsNullOrWhiteSpace($VMName)) { throw '-EnsureExistingAutoLogon requires the exact existing -VMName.' }
    if ($PreflightOnly -or $NoLaunch -or $ResumeIncomplete -or $ReplaceIncompleteReplica -or $ReuseLatestBackup -or -not [string]::IsNullOrWhiteSpace($BackupTargetVhdPath) -or -not [string]::IsNullOrWhiteSpace($RemoveFailedBackupRoot)) {
        throw '-EnsureExistingAutoLogon is a bounded existing-VM repair/verification mode and cannot be combined with capture, resume, replacement, backup-target, cleanup, preflight, or no-launch switches.'
    }
    $CodexDesktopReplica = $true
    $NetworkMode = 'DefaultSwitch'
}

if ($CodexDesktopReplica) {
    # Every discovered Codex application, identity, and session store is on the
    # Windows volume. Keeping unrelated fixed data disks out of this mode makes
    # the point-in-time replica both deterministic and independently verifiable.
    $SkipFixedDataVolumes = $true
    if (-not $PSBoundParameters.ContainsKey('NetworkMode')) { $NetworkMode = 'DefaultSwitch' }
    if (-not $NoLaunch -and $NetworkMode -ne 'DefaultSwitch') {
        throw 'CodexDesktopReplica runtime validation requires -NetworkMode DefaultSwitch.'
    }
}

if ($ReplaceIncompleteReplica -and ($ResumeIncomplete -or $ReuseLatestBackup -or $PreflightOnly)) {
    throw '-ReplaceIncompleteReplica requires a fresh non-preflight capture and cannot be combined with -ResumeIncomplete or -ReuseLatestBackup.'
}

if (-not ('ReplicaNativeMethods' -as [type])) {
    Add-Type -TypeDefinition @'
using System;
using System.Runtime.InteropServices;
using System.Security;
using System.Text;

public static class ReplicaNativeMethods
{
    [StructLayout(LayoutKind.Sequential)]
    private struct LSA_UNICODE_STRING
    {
        public ushort Length;
        public ushort MaximumLength;
        public IntPtr Buffer;
    }

    [StructLayout(LayoutKind.Sequential)]
    private struct LSA_OBJECT_ATTRIBUTES
    {
        public uint Length;
        public IntPtr RootDirectory;
        public LSA_UNICODE_STRING ObjectName;
        public uint Attributes;
        public IntPtr SecurityDescriptor;
        public IntPtr SecurityQualityOfService;
    }

    [DllImport("kernel32.dll", CharSet = CharSet.Unicode, SetLastError = true)]
    [return: MarshalAs(UnmanagedType.Bool)]
    public static extern bool DefineDosDevice(uint flags, string deviceName, string targetPath);

    [DllImport("kernel32.dll", CharSet = CharSet.Unicode, SetLastError = true)]
    public static extern uint QueryDosDevice(string deviceName, StringBuilder targetPath, int maximumLength);

    [DllImport("advapi32.dll")]
    private static extern uint LsaOpenPolicy(IntPtr systemName, ref LSA_OBJECT_ATTRIBUTES objectAttributes, uint desiredAccess, out IntPtr policyHandle);

    [DllImport("advapi32.dll")]
    private static extern uint LsaRetrievePrivateData(IntPtr policyHandle, ref LSA_UNICODE_STRING keyName, out IntPtr privateData);

    [DllImport("advapi32.dll")]
    private static extern uint LsaNtStatusToWinError(uint status);

    [DllImport("advapi32.dll")]
    private static extern uint LsaFreeMemory(IntPtr buffer);

    [DllImport("advapi32.dll")]
    private static extern uint LsaClose(IntPtr handle);

    [DllImport("advapi32.dll", CharSet = CharSet.Unicode, SetLastError = true)]
    [return: MarshalAs(UnmanagedType.Bool)]
    private static extern bool LogonUser(string userName, string domain, string password, int logonType, int logonProvider, out IntPtr token);

    [DllImport("kernel32.dll")]
    [return: MarshalAs(UnmanagedType.Bool)]
    private static extern bool CloseHandle(IntPtr handle);

    public static bool ValidateAutoLogonCredential(string userName, string domain, out bool secretRetrieved, out int lsaError, out int logonError)
    {
        const uint POLICY_GET_PRIVATE_INFORMATION = 0x00000004;
        const int LOGON32_LOGON_INTERACTIVE = 2;
        const int LOGON32_PROVIDER_DEFAULT = 0;
        secretRetrieved = false;
        lsaError = 0;
        logonError = 0;
        IntPtr policy = IntPtr.Zero;
        IntPtr keyBuffer = IntPtr.Zero;
        IntPtr privateData = IntPtr.Zero;
        IntPtr token = IntPtr.Zero;
        string password = null;

        try
        {
            LSA_OBJECT_ATTRIBUTES attributes = new LSA_OBJECT_ATTRIBUTES();
            attributes.Length = (uint)Marshal.SizeOf(typeof(LSA_OBJECT_ATTRIBUTES));
            uint status = LsaOpenPolicy(IntPtr.Zero, ref attributes, POLICY_GET_PRIVATE_INFORMATION, out policy);
            if (status != 0)
            {
                lsaError = (int)LsaNtStatusToWinError(status);
                return false;
            }

            const string secretName = "DefaultPassword";
            keyBuffer = Marshal.StringToHGlobalUni(secretName);
            LSA_UNICODE_STRING keyName = new LSA_UNICODE_STRING();
            keyName.Buffer = keyBuffer;
            keyName.Length = (ushort)(secretName.Length * 2);
            keyName.MaximumLength = (ushort)((secretName.Length + 1) * 2);
            status = LsaRetrievePrivateData(policy, ref keyName, out privateData);
            if (status != 0)
            {
                lsaError = (int)LsaNtStatusToWinError(status);
                return false;
            }

            LSA_UNICODE_STRING secret = (LSA_UNICODE_STRING)Marshal.PtrToStructure(privateData, typeof(LSA_UNICODE_STRING));
            if (secret.Buffer == IntPtr.Zero)
            {
                lsaError = 1168;
                return false;
            }

            password = Marshal.PtrToStringUni(secret.Buffer, secret.Length / 2);
            secretRetrieved = true;
            bool valid = LogonUser(userName, domain, password, LOGON32_LOGON_INTERACTIVE, LOGON32_PROVIDER_DEFAULT, out token);
            if (!valid)
            {
                logonError = Marshal.GetLastWin32Error();
                return false;
            }
            return true;
        }
        finally
        {
            password = null;
            if (token != IntPtr.Zero) { CloseHandle(token); }
            if (privateData != IntPtr.Zero) { LsaFreeMemory(privateData); }
            if (keyBuffer != IntPtr.Zero) { Marshal.FreeHGlobal(keyBuffer); }
            if (policy != IntPtr.Zero) { LsaClose(policy); }
        }
    }

    public static SecureString GetAutoLogonSecurePassword(out int lsaError)
    {
        const uint POLICY_GET_PRIVATE_INFORMATION = 0x00000004;
        lsaError = 0;
        IntPtr policy = IntPtr.Zero;
        IntPtr keyBuffer = IntPtr.Zero;
        IntPtr privateData = IntPtr.Zero;
        SecureString securePassword = null;

        try
        {
            LSA_OBJECT_ATTRIBUTES attributes = new LSA_OBJECT_ATTRIBUTES();
            attributes.Length = (uint)Marshal.SizeOf(typeof(LSA_OBJECT_ATTRIBUTES));
            uint status = LsaOpenPolicy(IntPtr.Zero, ref attributes, POLICY_GET_PRIVATE_INFORMATION, out policy);
            if (status != 0)
            {
                lsaError = (int)LsaNtStatusToWinError(status);
                return null;
            }

            const string secretName = "DefaultPassword";
            keyBuffer = Marshal.StringToHGlobalUni(secretName);
            LSA_UNICODE_STRING keyName = new LSA_UNICODE_STRING();
            keyName.Buffer = keyBuffer;
            keyName.Length = (ushort)(secretName.Length * 2);
            keyName.MaximumLength = (ushort)((secretName.Length + 1) * 2);
            status = LsaRetrievePrivateData(policy, ref keyName, out privateData);
            if (status != 0)
            {
                lsaError = (int)LsaNtStatusToWinError(status);
                return null;
            }

            LSA_UNICODE_STRING secret = (LSA_UNICODE_STRING)Marshal.PtrToStructure(privateData, typeof(LSA_UNICODE_STRING));
            if (secret.Buffer == IntPtr.Zero || secret.Length == 0)
            {
                lsaError = 1168;
                return null;
            }

            securePassword = new SecureString();
            for (int index = 0; index < secret.Length / 2; index++)
            {
                securePassword.AppendChar((char)Marshal.ReadInt16(secret.Buffer, index * 2));
            }
            securePassword.MakeReadOnly();
            return securePassword;
        }
        finally
        {
            if (privateData != IntPtr.Zero) { LsaFreeMemory(privateData); }
            if (keyBuffer != IntPtr.Zero) { Marshal.FreeHGlobal(keyBuffer); }
            if (policy != IntPtr.Zero) { LsaClose(policy); }
        }
    }
}
'@
}


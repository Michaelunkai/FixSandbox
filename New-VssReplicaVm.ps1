        [string[]]$ExcludedDirectoryNames,
        [string]$CopyLog,
        [uint64]$ExpectedSourceUsedBytes
    )

    $sourceRoot = Get-Item -LiteralPath $Source -Force
    $destinationRoot = Get-Item -LiteralPath $Destination -Force
    if (($sourceRoot.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0) {
        throw "Robocopy source root $Source is a reparse point; refusing a link-only false positive."
    }
    if (($destinationRoot.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0) {
        throw "Robocopy destination root $Destination became a reparse point; no VM will be launched."
    }

    $logErrors = @(Select-String -LiteralPath $CopyLog -Pattern '(?i)\bERROR\s+\d+\s+\(0x[0-9a-f]+\)' -ErrorAction SilentlyContinue)
    if ($logErrors.Count -gt 0) {
        throw "Robocopy's final verification log contains $($logErrors.Count) error(s). See $CopyLog."
    }

    $excluded = @{}
    foreach ($name in $ExcludedDirectoryNames) {
        if (-not [string]::IsNullOrWhiteSpace($name)) { $excluded[$name] = $true }
    }
    $sourcePrefix = $Source.TrimEnd('\')
    $includedRootItems = @(
        Get-ChildItem -LiteralPath $Source -Force | Where-Object {
            -not ($_.PSIsContainer -and $excluded.ContainsKey($_.Name))
        }
    )
    foreach ($sourceItem in $includedRootItems) {
        $destinationItemPath = Join-Path $Destination $sourceItem.Name
        $destinationItem = Get-Item -LiteralPath $destinationItemPath -Force -ErrorAction SilentlyContinue
        if ($null -eq $destinationItem) {
            throw "Root-entry parity failed: $($sourceItem.FullName) is missing from $Destination."
        }
        if ([bool]$sourceItem.PSIsContainer -ne [bool]$destinationItem.PSIsContainer) {
            throw "Root-entry type parity failed for $($sourceItem.FullName)."
        }
        if (-not $sourceItem.PSIsContainer -and [uint64]$sourceItem.Length -ne [uint64]$destinationItem.Length) {
            throw "Root-file length parity failed for $($sourceItem.FullName)."
        }
    }

    $sampleFiles = [System.Collections.Generic.List[object]]::new()
    $directoryQueue = [System.Collections.Generic.Queue[object]]::new()
    foreach ($item in $includedRootItems) {
        if ($item.PSIsContainer) {
            if (($item.Attributes -band [IO.FileAttributes]::ReparsePoint) -eq 0) {
                $directoryQueue.Enqueue($item)
            }
        }
        elseif (($item.Attributes -band [IO.FileAttributes]::ReparsePoint) -eq 0) {
            $sampleFiles.Add($item)
        }
    }
    $examinedDirectories = 0
    while ($sampleFiles.Count -lt 5 -and $directoryQueue.Count -gt 0 -and $examinedDirectories -lt 256) {
        $directory = $directoryQueue.Dequeue()
        $examinedDirectories++
        foreach ($item in @(Get-ChildItem -LiteralPath $directory.FullName -Force -ErrorAction SilentlyContinue)) {
            if ($item.PSIsContainer) {
                if (-not $excluded.ContainsKey($item.Name) -and ($item.Attributes -band [IO.FileAttributes]::ReparsePoint) -eq 0) {
                    $directoryQueue.Enqueue($item)
                }
            }
            elseif (($item.Attributes -band [IO.FileAttributes]::ReparsePoint) -eq 0) {
                $sampleFiles.Add($item)
                if ($sampleFiles.Count -ge 5) { break }
            }
        }
    }

    $sampleChecks = [System.Collections.Generic.List[object]]::new()
    foreach ($sourceFile in @($sampleFiles | Select-Object -First 5)) {
        $relativePath = $sourceFile.FullName.Substring($sourcePrefix.Length).TrimStart('\')
        $destinationFilePath = Join-Path $Destination $relativePath
        $destinationFile = Get-Item -LiteralPath $destinationFilePath -Force -ErrorAction SilentlyContinue
        if ($null -eq $destinationFile -or $destinationFile.PSIsContainer -or [uint64]$destinationFile.Length -ne [uint64]$sourceFile.Length) {
            throw "Sample-file parity failed for $relativePath."
        }
        $hashVerified = $false
        if ([uint64]$sourceFile.Length -le 64MB) {
            $sourceHash = (Get-FileHash -LiteralPath $sourceFile.FullName -Algorithm SHA256).Hash
            $destinationHash = (Get-FileHash -LiteralPath $destinationFilePath -Algorithm SHA256).Hash
            if ($sourceHash -ne $destinationHash) { throw "Sample SHA-256 parity failed for $relativePath." }
            $hashVerified = $true
        }
        $sampleChecks.Add([pscustomobject]@{ RelativePath = $relativePath; Length = [uint64]$sourceFile.Length; Sha256Verified = $hashVerified })
    }

    $destinationDriveLetter = $Destination.Substring(0, 1)
    $destinationVolume = Get-Volume -DriveLetter $destinationDriveLetter
    $destinationUsedBytes = [uint64]($destinationVolume.Size - $destinationVolume.SizeRemaining)
    $minimumExpectedUsedBytes = [uint64]0
    if ($ExpectedSourceUsedBytes -ge 10GB) {
        $minimumExpectedUsedBytes = [uint64][math]::Max(512MB, [double]$ExpectedSourceUsedBytes * 0.005)
        if ($destinationUsedBytes -lt $minimumExpectedUsedBytes) {
            throw "Destination $Destination contains only $destinationUsedBytes used bytes; at least $minimumExpectedUsedBytes were required as an anti-empty-copy gate."
        }
    }

    Write-ReplicaLog PASS "Independent mirror evidence passed for ${Source}: normal roots, clean log, $($includedRootItems.Count) included root entries, $($sampleChecks.Count) sampled files, and $destinationUsedBytes used destination bytes."
    return [pscustomobject]@{
        FinalLogErrorCount = 0
        IncludedRootEntryCount = $includedRootItems.Count
        SampleChecks = @($sampleChecks)
        DestinationUsedBytes = $destinationUsedBytes
        MinimumExpectedUsedBytes = $minimumExpectedUsedBytes
    }
}

function Invoke-VerifiedRobocopyMirror {
    param(
        [string]$Source,
        [string]$Destination,
        [string]$FileSystem,
        [string[]]$ExcludedDirectoryNames,
        [string]$CopyLog,
        [int]$MaximumPasses,
        [uint64]$ExpectedSourceUsedBytes
    )

    $copyMode = if ($FileSystem -eq 'NTFS') { '/COPYALL' } else { '/COPY:DAT' }
    $metadataRepairModes = if ($FileSystem -eq 'NTFS') { @('/SECFIX', '/TIMFIX') } else { @() }
    for ($pass = 1; $pass -le $MaximumPasses; $pass++) {
        $arguments = [System.Collections.Generic.List[string]]::new()
        foreach ($argument in @(
            $Source, $Destination, '*', '/MIR', $copyMode, '/DCOPY:DAT', '/B', '/SL', '/SJ',
            '/R:2', '/W:1', '/MT:32', '/NP', "/LOG:$CopyLog"
        )) { $arguments.Add($argument) }
        foreach ($argument in $metadataRepairModes) { $arguments.Add($argument) }
        foreach ($name in $ExcludedDirectoryNames) {
            $arguments.Add('/XD')
            $arguments.Add($name)
        }
        Write-ReplicaLog INFO "Robocopy mirror pass $pass/$MaximumPasses for $Source."
        & (Join-Path $env:WINDIR 'System32\robocopy.exe') @arguments | Out-Null
        $exitCode = $LASTEXITCODE
        if ($exitCode -ge 8) {
            throw "Robocopy failed for $Source with exit code $exitCode. See $CopyLog."
        }
        if ($exitCode -eq 0) {
            $evidence = Test-RobocopyMirrorEvidence -Source $Source -Destination $Destination -ExcludedDirectoryNames $ExcludedDirectoryNames -CopyLog $CopyLog -ExpectedSourceUsedBytes $ExpectedSourceUsedBytes
            Write-ReplicaLog PASS "Robocopy reports an exact stabilized mirror for $Source after $pass pass(es), confirmed by independent evidence."
            return [pscustomobject]@{ Passes = $pass; FinalExitCode = 0; Log = $CopyLog; Evidence = $evidence }
        }
    }
    throw "Source $Source did not stabilize after $MaximumPasses Robocopy passes. No VM will be launched."
}

function New-FixedDataDiskReplica {
    param(
        [object]$Plan,
        [string]$BasePath,
        [string]$ChildPath,
        [string]$CopyLogRoot,
        [string[]]$GeneratedDirectoryExclusions,
        [int]$MaximumPasses,
        [switch]$UseLiveStabilizedSource
    )

    $shadows = @{}
    $accesses = [System.Collections.Generic.List[object]]::new()
    $mounted = $false
    $virtualDisk = $null
    try {
        foreach ($volume in $Plan.Volumes) {
            if ($volume.FileSystem -eq 'NTFS' -and -not $UseLiveStabilizedSource) {
                $shadows[$volume.DriveLetter] = New-DataVolumeShadow -DriveLetter $volume.DriveLetter
            }
            elseif ($volume.FileSystem -eq 'NTFS') {
                Write-ReplicaLog INFO "Using repeated, fail-closed live mirror passes for $($volume.DriveLetter): because its replica is stored on the same physical disk."
            }
        }

        New-Item -ItemType Directory -Path (Split-Path -Parent $BasePath), (Split-Path -Parent $ChildPath), $CopyLogRoot -Force | Out-Null
        Write-ReplicaLog INFO "Creating dynamic data-disk base for source disk $($Plan.DiskNumber) at $BasePath."
        New-VHD -Path $BasePath -Dynamic -SizeBytes $Plan.Size -BlockSizeBytes 2MB -LogicalSectorSizeBytes $Plan.LogicalSectorSize -PhysicalSectorSizeBytes $Plan.PhysicalSectorSize | Out-Null
        $virtualDisk = Mount-VHD -Path $BasePath -Passthru
        $mounted = $true
        Initialize-Disk -Number $virtualDisk.DiskNumber -PartitionStyle MBR | Out-Null

        $copies = [System.Collections.Generic.List[object]]::new()
        foreach ($sourceVolume in $Plan.Volumes | Sort-Object PartitionNumber) {
            $newPartition = New-Partition -DiskNumber $virtualDisk.DiskNumber -Offset $sourceVolume.Offset -Size $sourceVolume.Size -MbrType IFS -IsActive:$sourceVolume.IsActive
            Format-Volume -Partition $newPartition -FileSystem $sourceVolume.FileSystem -NewFileSystemLabel $sourceVolume.FileSystemLabel -AllocationUnitSize $sourceVolume.AllocationUnitSize -Force -Confirm:$false | Out-Null
            if ($sourceVolume.MbrType -ne 7) {
                Set-MbrPartitionIdWithDiskPart -DiskNumber $virtualDisk.DiskNumber -PartitionNumber $newPartition.PartitionNumber -MbrType $sourceVolume.MbrType
            }
            $access = Add-TemporaryAccessPath -DiskNumber $virtualDisk.DiskNumber -PartitionNumber $newPartition.PartitionNumber
            $accesses.Add([pscustomobject]@{ PartitionNumber = $newPartition.PartitionNumber; Access = $access })
            $sourceRoot = if ($shadows.ContainsKey($sourceVolume.DriveLetter)) {
                [string]$shadows[$sourceVolume.DriveLetter].Root
            }
            else {
                "$($sourceVolume.DriveLetter):\"
            }
            $copyLog = Join-Path $CopyLogRoot "Drive-$($sourceVolume.DriveLetter)-Robocopy.log"
            $copy = Invoke-VerifiedRobocopyMirror -Source $sourceRoot -Destination $access.Root -FileSystem $sourceVolume.FileSystem -ExcludedDirectoryNames $GeneratedDirectoryExclusions -CopyLog $copyLog -MaximumPasses $MaximumPasses -ExpectedSourceUsedBytes $sourceVolume.UsedBytes
            $sourceMode = if ($shadows.ContainsKey($sourceVolume.DriveLetter)) { 'VSS snapshot' } else { 'Live stabilized mirror' }
            $copies.Add([pscustomobject]@{ DriveLetter = "$($sourceVolume.DriveLetter):"; Source = $sourceRoot; SourceMode = $sourceMode; Result = $copy })
        }

        foreach ($item in $accesses) {
            if ($item.Access.Added) {
                Remove-PartitionAccessPath -DiskNumber $virtualDisk.DiskNumber -PartitionNumber $item.PartitionNumber -AccessPath $item.Access.Root
            }
        }
        $accesses.Clear()
        Set-Disk -Number $virtualDisk.DiskNumber -Signature $Plan.Signature

        $actualDisk = Get-Disk -Number $virtualDisk.DiskNumber
        if ([uint32]$actualDisk.Signature -ne [uint32]$Plan.Signature) {
            throw "Cloned disk signature verification failed for source disk $($Plan.DiskNumber)."
        }
        foreach ($sourceVolume in $Plan.Volumes) {
            $actualPartition = Get-Partition -DiskNumber $virtualDisk.DiskNumber -PartitionNumber $sourceVolume.PartitionNumber
            if (
                [uint64]$actualPartition.Offset -ne [uint64]$sourceVolume.Offset -or
                [uint64]$actualPartition.Size -ne [uint64]$sourceVolume.Size -or
                [byte]$actualPartition.MbrType -ne [byte]$sourceVolume.MbrType -or
                [bool]$actualPartition.IsActive -ne [bool]$sourceVolume.IsActive
            ) {
                throw "Partition layout verification failed for $($sourceVolume.DriveLetter):."
            }
            $actualVolume = $actualPartition | Get-Volume
            if (
                [string]$actualVolume.FileSystem -ne [string]$sourceVolume.FileSystem -or
                [string]$actualVolume.FileSystemLabel -ne [string]$sourceVolume.FileSystemLabel -or
                [uint32]$actualVolume.AllocationUnitSize -ne [uint32]$sourceVolume.AllocationUnitSize
            ) {
                throw "Filesystem identity verification failed for $($sourceVolume.DriveLetter):."
            }
        }
        Dismount-VHD -Path $BasePath
        $mounted = $false

        New-VHD -Path $ChildPath -ParentPath $BasePath -Differencing | Out-Null
        $child = Get-VHD -Path $ChildPath
        if ($child.ParentPath -ne $BasePath -or $child.VhdType -ne 'Differencing') {
            throw "Data disk $($Plan.DiskNumber) differencing chain verification failed."
        }
        Write-ReplicaLog PASS "Data disk $($Plan.DiskNumber) structure, identity, filesystems, mirrors, and child chain are verified."
        return [pscustomobject]@{
            SourceDiskNumber = $Plan.DiskNumber
            SourceDiskName = $Plan.FriendlyName
            Signature = $Plan.Signature
            Base = $BasePath
            Child = $ChildPath
            Volumes = $Plan.Volumes
            Copies = @($copies)
        }
    }
    finally {
        foreach ($item in $accesses) {
            if ($item.Access.Added -and $null -ne $virtualDisk) {
                Remove-PartitionAccessPath -DiskNumber $virtualDisk.DiskNumber -PartitionNumber $item.PartitionNumber -AccessPath $item.Access.Root -ErrorAction SilentlyContinue
            }
        }
        if ($mounted) { Dismount-VHD -Path $BasePath -ErrorAction SilentlyContinue }
        foreach ($shadow in @($shadows.Values)) { Remove-DataVolumeShadow -Shadow $shadow }
    }
}


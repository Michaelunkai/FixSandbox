function Test-Administrator {
    $identity = [Security.Principal.WindowsIdentity]::GetCurrent()
    $principal = [Security.Principal.WindowsPrincipal]::new($identity)
    if (-not $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
        throw 'Run this script from an elevated Administrator PowerShell session.'
    }
    Write-ReplicaLog PASS "Running elevated as $($identity.Name)."
}

function New-ReplicaGuestCredential {
    param(
        [string]$ComputerName,
        [string]$UserName
    )

    [int]$lsaError = 0
    $securePassword = [ReplicaNativeMethods]::GetAutoLogonSecurePassword([ref]$lsaError)
    if ($null -eq $securePassword) {
        throw "Could not obtain the already-validated auto-logon credential as a SecureString for PowerShell Direct (LSA=$lsaError)."
    }
    try {
        return [System.Management.Automation.PSCredential]::new("$ComputerName\$UserName", $securePassword)
    }
    catch {
        $securePassword.Dispose()
        throw
    }
}

function Get-ReplicaServiceState {
    param([string[]]$Names)

    return @($Names | ForEach-Object {
        $service = Get-Service -Name $_ -ErrorAction Stop
        [pscustomobject]@{
            Name = $service.Name
            StartType = [string]$service.StartType
            Status = [string]$service.Status
        }
    })
}


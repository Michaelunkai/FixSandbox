function Get-GuestKvp {
    param(
        [object]$VM,
        [switch]$Custom
    )

    $computerSystem = Get-CimInstance -Namespace 'root\virtualization\v2' -ClassName Msvm_ComputerSystem |
        Where-Object { $_.Name -eq [string]$VM.Id }
    $component = Get-CimAssociatedInstance -InputObject $computerSystem -ResultClassName Msvm_KvpExchangeComponent -ErrorAction SilentlyContinue
    $values = [ordered]@{}
    if ($null -eq $component) { return [pscustomobject]$values }
    $items = if ($Custom) { @($component.GuestExchangeItems) } else { @($component.GuestIntrinsicExchangeItems) }
    foreach ($item in $items) {
        try {
            [xml]$xml = $item
            $properties = @{}
            foreach ($property in $xml.INSTANCE.PROPERTY) { $properties[$property.NAME] = $property.VALUE }
            if ($properties.Name) { $values[[string]$properties.Name] = [string]$properties.Data }
        }
        catch { }
    }
    return [pscustomobject]$values
}


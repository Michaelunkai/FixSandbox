function Move-WindowsBackupToProtectedArchive {
    param(
        [string]$Target,
        [string]$ArchiveParent,
        [string]$Stamp
    )

    $source = Join-Path "${Target}\" 'WindowsImageBackup'
    if (-not (Test-Path -LiteralPath $source -PathType Container)) {
        throw "Fresh Windows Backup output was not found at $source."
    }
    New-Item -ItemType Directory -Path $ArchiveParent -Force | Out-Null
    $destination = Join-Path $ArchiveParent "WindowsImageBackup-$Stamp"
    if (Test-Path -LiteralPath $destination) {
        throw "Protected backup archive already exists: $destination"
    }
    Move-Item -LiteralPath $source -Destination $destination -ErrorAction Stop
    if ((Test-Path -LiteralPath $source) -or -not (Test-Path -LiteralPath $destination -PathType Container)) {
        throw "Windows Backup was not moved completely into $destination."
    }
    Write-ReplicaLog PASS "Moved the fresh Windows Backup into protected storage at $destination."
    return $destination
}

function Get-LatestProtectedBackupRoot {
    param(
        [string]$Target,
        [string]$ArchiveParent
    )

    $roots = [System.Collections.Generic.List[string]]::new()
    $direct = Join-Path "${Target}\" 'WindowsImageBackup'
    if (Test-Path -LiteralPath $direct -PathType Container) { $roots.Add($direct) }
    if (Test-Path -LiteralPath $ArchiveParent -PathType Container) {
        foreach ($candidate in Get-ChildItem -LiteralPath $ArchiveParent -Directory -Filter 'WindowsImageBackup-*' -ErrorAction SilentlyContinue) {
            $roots.Add($candidate.FullName)
        }
    }

    $candidates = foreach ($root in $roots) {
        $machineRoot = Join-Path $root $env:COMPUTERNAME
        if (-not (Test-Path -LiteralPath $machineRoot -PathType Container)) { continue }
        $latestSet = Get-ChildItem -LiteralPath $machineRoot -Directory -ErrorAction SilentlyContinue |
            Where-Object Name -like 'Backup *' |
            Sort-Object LastWriteTime -Descending |
            Select-Object -First 1
        if ($null -ne $latestSet) {
            [pscustomobject]@{ Root = $root; LastWriteTime = $latestSet.LastWriteTime }
        }
    }
    $selected = $candidates | Sort-Object LastWriteTime -Descending | Select-Object -First 1
    if ($null -eq $selected) {
        throw "No reusable Windows Backup exists at $direct or beneath $ArchiveParent."
    }
    return [string]$selected.Root
}

function Get-VssWriterHealth {
    $output = @(& (Join-Path $env:WINDIR 'System32\vssadmin.exe') list writers 2>&1)
    if ($LASTEXITCODE -ne 0) { throw 'vssadmin could not enumerate VSS writers.' }
    $writerCount = @($output | Where-Object { [string]$_ -match '^Writer name:' }).Count
    $failedLines = @($output | Where-Object {
        ([string]$_ -match '^\s*State:' -and [string]$_ -notmatch '\[1\]\s+Stable') -or
        ([string]$_ -match '^\s*Last error:' -and [string]$_ -notmatch 'Last error:\s+No error')
    })
    return [pscustomobject]@{
        WriterCount = $writerCount
        Healthy = ($writerCount -gt 0 -and $failedLines.Count -eq 0)
        FailedLines = $failedLines
        Text = ($output -join [Environment]::NewLine)
    }
}

function Repair-VssWriterHealth {
    if (Get-Process wbadmin -ErrorAction SilentlyContinue) {
        throw 'Cannot reset VSS writers while wbadmin is active.'
    }

    Write-ReplicaLog WARN 'Resetting the VSS writer service chain after an unhealthy writer state.'
    $restoreNames = [System.Collections.Generic.List[string]]::new()
    foreach ($name in @('AppIDSvc', 'applockerfltr', 'vmms', 'HgClientService')) {
        $service = Get-Service -Name $name -ErrorAction SilentlyContinue
        if ($null -ne $service -and $service.Status -eq 'Running') { $restoreNames.Add($name) }
    }

    Stop-Service -Name wbengine -Force -ErrorAction SilentlyContinue
    Stop-Service -Name swprv -Force -ErrorAction SilentlyContinue
    Stop-Service -Name VSS -Force -ErrorAction SilentlyContinue
    Restart-Service -Name CryptSvc -Force
    try {
        Restart-Service -Name Winmgmt -Force -ErrorAction Stop
    }
    catch {
        Write-ReplicaLog WARN "Winmgmt did not accept a direct restart; continuing with writer re-registration validation: $($_.Exception.Message)"
    }
    if ((Get-Service -Name CryptSvc).Status -ne 'Running') { Start-Service -Name CryptSvc }
    if ((Get-Service -Name Winmgmt).Status -ne 'Running') { Start-Service -Name Winmgmt }
    foreach ($name in $restoreNames) {
        $service = Get-Service -Name $name -ErrorAction SilentlyContinue
        if ($null -ne $service -and $service.Status -ne 'Running') { Start-Service -Name $name }
    }
    Start-Service -Name EventSystem
    Start-Service -Name COMSysApp -ErrorAction SilentlyContinue
    Start-Service -Name VSS
    Start-Service -Name swprv
    Initialize-StorageManagement
    Start-Sleep -Seconds 5

    $health = Get-VssWriterHealth
    if (-not $health.Healthy) {
        throw "VSS writers remain unhealthy after the controlled service reset: $($health.FailedLines -join '; ')"
    }
    Write-ReplicaLog PASS "All $($health.WriterCount) VSS writers are Stable after the controlled reset."
}

function Assert-VssWriterHealth {
    $health = Get-VssWriterHealth
    if (-not $health.Healthy) {
        Repair-VssWriterHealth
        return
    }
    Write-ReplicaLog PASS "All $($health.WriterCount) VSS writers are Stable."
}

function Invoke-WindowsBackup {
    param([string]$Target)

    foreach ($serviceName in @('VSS', 'swprv', 'wbengine')) {
        $service = Get-Service -Name $serviceName -ErrorAction Stop
        if ($service.StartType -eq [System.ServiceProcess.ServiceStartMode]::Disabled) {
            Set-Service -Name $serviceName -StartupType Manual
        }
        if ((Get-Service -Name $serviceName).Status -ne 'Running') {
            Start-Service -Name $serviceName
        }
    }

    $systemVolume = $env:SystemDrive.TrimEnd(':') + ':'
    for ($attempt = 1; $attempt -le 2; $attempt++) {
        Assert-VssWriterHealth
        Write-ReplicaLog INFO "Starting VSS-aware Windows Backup of $systemVolume plus all critical volumes to $Target (attempt $attempt/2)."
        $output = & wbadmin.exe start backup "-backupTarget:$Target" "-include:$systemVolume" -allCritical -vssCopy -quiet 2>&1
        $exitCode = $LASTEXITCODE
        foreach ($line in $output) { Write-ReplicaLog INFO ([string]$line) }
        if ($exitCode -eq 0) {
            Stop-Service -Name wbengine -Force -ErrorAction SilentlyContinue
            (Get-Service -Name wbengine).WaitForStatus([System.ServiceProcess.ServiceControllerStatus]::Stopped, [TimeSpan]::FromSeconds(30))
            Write-ReplicaLog PASS 'Windows Backup completed successfully.'
            return
        }
        $outputText = @($output | ForEach-Object { [string]$_ }) -join [Environment]::NewLine
        if ($outputText -match '(?i)not enough space|0x80070070') {
            throw "wbadmin stopped because $Target has insufficient free space; a VSS reset/retry cannot repair a capacity failure."
        }
        if ($attempt -eq 1) {
            Write-ReplicaLog WARN "wbadmin failed with exit code $exitCode; performing one controlled VSS recovery before retrying."
            Repair-VssWriterHealth
        }
        else {
            throw "wbadmin failed with exit code $exitCode after two attempts."
        }
    }
}

function Copy-VhdBase {
    param(
        [object]$Record,
        [string]$Destination
    )

    Write-ReplicaLog INFO "Copying self-contained $($Record.Role) VHDX base to $Destination."
    Copy-Item -LiteralPath $Record.Path -Destination $Destination
    $sourceVhd = Get-VHD -Path $Record.Path
    $destinationVhd = Get-VHD -Path $Destination
    if (
        $sourceVhd.Size -ne $destinationVhd.Size -or
        $sourceVhd.VhdFormat -ne $destinationVhd.VhdFormat -or
        (Get-Item -LiteralPath $Record.Path).Length -ne (Get-Item -LiteralPath $Destination).Length
    ) {
        throw "$($Record.Role) base VHDX failed structural copy verification."
    }
    Write-ReplicaLog PASS "$($Record.Role) base VHDX is self-contained and structurally verified."
}

function Set-PortableEfiStore {
    param([string]$EfiVhd)

    $bcdBytes = [Convert]::FromBase64String(($portableBcdBase64 -replace '\s', ''))
    $actualAssetHash = Get-ByteArraySha256 -Bytes $bcdBytes
    if ($actualAssetHash -ne $portableBcdSha256) {
        throw "Portable BCD asset hash mismatch: expected $portableBcdSha256, got $actualAssetHash."
    }

    $mounted = $false
    $access = $null
    try {
        $disk = Mount-VHD -Path $EfiVhd -Passthru
        $mounted = $true
        $candidates = @(Get-Partition -DiskNumber $disk.DiskNumber | Where-Object { $_.GptType -ne $msrGptType })
        if ($candidates.Count -ne 1) {
            throw "Expected one non-MSR partition in EFI VHDX; found $($candidates.Count)."
        }
        $partition = $candidates[0]
        if ($partition.GptType -ne $efiGptType) {
            Set-Partition -DiskNumber $disk.DiskNumber -PartitionNumber $partition.PartitionNumber -GptType $efiGptType
        }
        $access = Add-TemporaryAccessPath -DiskNumber $disk.DiskNumber -PartitionNumber $partition.PartitionNumber
        $destination = Join-Path $access.Root 'EFI\Microsoft\Boot\BCD'
        $destinationDirectory = Split-Path -Parent $destination
        New-Item -ItemType Directory -Path $destinationDirectory -Force | Out-Null
        [IO.File]::WriteAllBytes($destination, $bcdBytes)
        $writtenHash = (Get-FileHash -LiteralPath $destination -Algorithm SHA256).Hash
        if ($writtenHash -ne $portableBcdSha256) {
            throw "EFI BCD write verification failed: expected $portableBcdSha256, got $writtenHash."
        }
        Write-ReplicaLog PASS 'EFI partition type and portable LOCATE-based BCD store are verified.'
    }
    finally {
        if ($mounted) {
            if ($null -ne $access -and $access.Added) {
                Remove-PartitionAccessPath -DiskNumber $disk.DiskNumber -PartitionNumber $partition.PartitionNumber -AccessPath $access.Root -ErrorAction SilentlyContinue
            }
            Dismount-VHD -Path $EfiVhd -ErrorAction SilentlyContinue
        }
    }
}


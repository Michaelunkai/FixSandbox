function Wait-CodexGuestReady {
    param(
        [string]$Name,
        [int]$TimeoutSeconds,
        [string]$ExpectedValidationId,
        [object]$Baseline,
        [System.Management.Automation.PSCredential]$Credential
    )

    $deadline = (Get-Date).AddSeconds($TimeoutSeconds)
    $expectedPassStatus = "PASS:$ExpectedValidationId"
    $expectedFailStatus = "FAIL:$ExpectedValidationId"
    do {
        $vm = Get-VM -Name $Name
        if ($vm.State -eq 'Off') { throw 'Codex guest powered off before runtime validation completed.' }
        $values = Get-GuestKvp -VM $vm -Custom
        $statusProperty = $values.PSObject.Properties['CodexReplicaStatus']
        if ($null -ne $statusProperty) {
            $status = [string]$statusProperty.Value
            if ($status -eq $expectedFailStatus) {
                try { $guestError = Get-CodexGuestFileViaPowerShellDirect -Name $Name -Credential $Credential -FileName 'error.txt' }
                catch { $guestError = 'The nonce-bound guest verifier reported failure, and its error artifact could not be retrieved.' }
                throw "Codex guest runtime validation failed: $guestError"
            }
            if ($status -eq $expectedPassStatus) {
                $evidence = Get-CodexGuestEvidenceViaPowerShellDirect -Name $Name -Credential $Credential
                Assert-CodexGuestEvidence -Evidence $evidence -ExpectedValidationId $ExpectedValidationId -Baseline $Baseline
                Write-ReplicaLog PASS "Codex guest runtime gates passed: fully decrypted portable C:, automatic device encryption blocked, persistent Admin auto-logon with no countdown or plaintext registry password, interactive Explorer desktop, VMConnect forced to Basic Session Mode so no RDP credential layer exists, credential-authenticated PowerShell Direct, $($evidence.KernelPolicyCheckCount) kernel-policy checks, package $($evidence.PackageVersion), $($evidence.SessionCount) session file(s), $($evidence.LoginStatus), authenticated model call, and responsive $($evidence.DesktopWindow) UI with the expected task visible."
                return $evidence
            }
        }
        Start-Sleep -Seconds 3
    } while ((Get-Date) -lt $deadline)
    throw "Codex guest did not publish conclusive runtime evidence within $TimeoutSeconds seconds."
}

function Wait-CodexGuestVerifierSignal {
    param(
        [string]$Name,
        [int]$TimeoutSeconds,
        [string]$ExpectedValidationId
    )

    $deadline = (Get-Date).AddSeconds($TimeoutSeconds)
    $expectedStatuses = @(
        "RUNNING:$ExpectedValidationId",
        "PASS:$ExpectedValidationId",
        "FAIL:$ExpectedValidationId"
    )
    do {
        $vm = Get-VM -Name $Name
        if ($vm.State -eq 'Off') { throw 'Codex guest powered off before its verifier could start.' }
        $values = Get-GuestKvp -VM $vm -Custom
        $statusProperty = $values.PSObject.Properties['CodexReplicaStatus']
        if ($null -ne $statusProperty -and [string]$statusProperty.Value -in $expectedStatuses) {
            Write-ReplicaLog PASS "Received nonce-bound Codex verifier startup signal from $Name."

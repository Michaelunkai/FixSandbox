        }
        Start-Sleep -Seconds 3
    } while ((Get-Date) -lt $deadline)
    return $false
}

function Wait-HealthyGuest {
    param(
        [string]$Name,
        [int]$TimeoutSeconds
    )

    $deadline = (Get-Date).AddSeconds($TimeoutSeconds)
    do {
        $vm = Get-VM -Name $Name
        if ($vm.State -eq 'Off') {
            throw 'Guest powered off before reaching a healthy heartbeat.'
        }
        $heartbeat = Get-VMIntegrationService -VMName $Name -Name Heartbeat -ErrorAction SilentlyContinue
        $kvp = Get-VMIntegrationService -VMName $Name -Name 'Key-Value Pair Exchange' -ErrorAction SilentlyContinue
        if (
            $vm.State -eq 'Running' -and
            $null -ne $heartbeat -and $heartbeat.PrimaryStatusDescription -eq 'OK' -and
            $null -ne $kvp -and $kvp.PrimaryStatusDescription -eq 'OK'
        ) {
            $guest = Get-GuestKvp -VM $vm
            if ($guest.OSVersion -and $guest.FullyQualifiedDomainName) {
                Write-ReplicaLog PASS "Guest heartbeat and KVP are healthy: $($guest.FullyQualifiedDomainName), $($guest.OSName), version $($guest.OSVersion)."
                return $guest
            }
        }
        Start-Sleep -Seconds 3
    } while ((Get-Date) -lt $deadline)
    throw "Guest did not provide healthy heartbeat plus OS identity within $TimeoutSeconds seconds."
}

function Reset-UnverifiedWindowsChild {
    param(
        [string]$Name,
        [string]$ReplicaPath,
        [string]$BasePath,
        [string]$ChildPath
    )

    $vm = Get-VM -Name $Name -ErrorAction Stop
    if ($vm.State -ne 'Off') { throw "Refusing to reset the Windows child while $Name is not powered off." }
    $replicaFull = [IO.Path]::GetFullPath($ReplicaPath).TrimEnd('\')
    $baseFull = [IO.Path]::GetFullPath($BasePath)
    $childFull = [IO.Path]::GetFullPath($ChildPath)
    $expectedBase = [IO.Path]::GetFullPath((Join-Path (Join-Path $replicaFull 'Bases') 'WindowsBase.vhdx'))
    $expectedChild = [IO.Path]::GetFullPath((Join-Path (Join-Path $replicaFull 'Disks') 'Windows.vhdx'))
    if (
        -not $baseFull.Equals($expectedBase, [StringComparison]::OrdinalIgnoreCase) -or
        -not $childFull.Equals($expectedChild, [StringComparison]::OrdinalIgnoreCase) -or
        -not (Test-Path -LiteralPath $baseFull -PathType Leaf) -or
        -not (Test-Path -LiteralPath $childFull -PathType Leaf)
    ) {
        throw 'Refusing to reset anything except the exact unverified Windows child beneath the exact replica root.'
    }
    $childVhd = Get-VHD -Path $childFull -ErrorAction Stop
    if ($childVhd.VhdType -ne 'Differencing' -or -not ([IO.Path]::GetFullPath([string]$childVhd.ParentPath)).Equals($baseFull, [StringComparison]::OrdinalIgnoreCase)) {
        throw 'The unverified Windows child does not have the exact verified immutable parent.'
    }
    $attached = @(Get-VMHardDiskDrive -VMName $Name | Where-Object {
        ([IO.Path]::GetFullPath([string]$_.Path)).Equals($childFull, [StringComparison]::OrdinalIgnoreCase)
    })
    if ($attached.Count -ne 1 -or $attached[0].ControllerType -ne 'SCSI' -or $attached[0].ControllerNumber -ne 0 -or $attached[0].ControllerLocation -ne 1) {
        throw 'The unverified Windows child is not the single expected VM disk at SCSI 0:1.'
    }

    $quarantine = "$childFull.unverified-$([Guid]::NewGuid().ToString('N'))"
    if (Test-Path -LiteralPath $quarantine) { throw "Unexpected Windows-child quarantine path already exists: $quarantine" }
    $driveRemoved = $false
    $oldMoved = $false
    $newCreated = $false
    $newAttached = $false
    try {
        Remove-VMHardDiskDrive -VMHardDiskDrive $attached[0] -ErrorAction Stop
        $driveRemoved = $true
        Move-Item -LiteralPath $childFull -Destination $quarantine -ErrorAction Stop
        $oldMoved = $true
        New-VHD -Path $childFull -ParentPath $baseFull -Differencing -ErrorAction Stop | Out-Null
        $newCreated = $true
        $replacement = Get-VHD -Path $childFull -ErrorAction Stop
        if ($replacement.VhdType -ne 'Differencing' -or -not ([IO.Path]::GetFullPath([string]$replacement.ParentPath)).Equals($baseFull, [StringComparison]::OrdinalIgnoreCase)) {
            throw 'Replacement Windows child failed its differencing-parent verification.'
        }
        Add-VMHardDiskDrive -VMName $Name -ControllerType SCSI -ControllerNumber 0 -ControllerLocation 1 -Path $childFull -ErrorAction Stop | Out-Null
        $newAttached = $true
        $verifiedAttachment = @(Get-VMHardDiskDrive -VMName $Name | Where-Object {
            $_.ControllerType -eq 'SCSI' -and $_.ControllerNumber -eq 0 -and $_.ControllerLocation -eq 1 -and
            ([IO.Path]::GetFullPath([string]$_.Path)).Equals($childFull, [StringComparison]::OrdinalIgnoreCase)
        })
        if ($verifiedAttachment.Count -ne 1) { throw 'Replacement Windows child was not attached exactly once at SCSI 0:1.' }
        Remove-Item -LiteralPath $quarantine -Force -ErrorAction Stop
        $oldMoved = $false
        Write-ReplicaLog PASS 'Reconstructed only the powered-off runtime-unverified Windows child from its independently audited immutable base and removed the superseded attempted-boot child.'
    }
    catch {
        $primaryFailure = $_.Exception
        $rollbackFailures = [System.Collections.Generic.List[string]]::new()
        try {
            if ($newAttached) {
                $replacementDrive = Get-VMHardDiskDrive -VMName $Name | Where-Object {
                    $_.ControllerType -eq 'SCSI' -and $_.ControllerNumber -eq 0 -and $_.ControllerLocation -eq 1
                } | Select-Object -First 1
                if ($null -ne $replacementDrive) { Remove-VMHardDiskDrive -VMHardDiskDrive $replacementDrive -ErrorAction Stop }
            }
        }
        catch { $rollbackFailures.Add($_.Exception.Message) }
        try {
            if ($newCreated -and (Test-Path -LiteralPath $childFull -PathType Leaf)) { Remove-Item -LiteralPath $childFull -Force -ErrorAction Stop }
        }
        catch { $rollbackFailures.Add($_.Exception.Message) }
        try {
            if ($oldMoved -and (Test-Path -LiteralPath $quarantine -PathType Leaf)) { Move-Item -LiteralPath $quarantine -Destination $childFull -ErrorAction Stop }
        }
        catch { $rollbackFailures.Add($_.Exception.Message) }
        try {
            if ($driveRemoved -and (Test-Path -LiteralPath $childFull -PathType Leaf)) {
                $restoredAttachment = @(Get-VMHardDiskDrive -VMName $Name | Where-Object {
                    ([IO.Path]::GetFullPath([string]$_.Path)).Equals($childFull, [StringComparison]::OrdinalIgnoreCase)
                })
                if ($restoredAttachment.Count -eq 0) {
                    Add-VMHardDiskDrive -VMName $Name -ControllerType SCSI -ControllerNumber 0 -ControllerLocation 1 -Path $childFull -ErrorAction Stop | Out-Null
                }
            }
        }
        catch { $rollbackFailures.Add($_.Exception.Message) }
        if ($rollbackFailures.Count -gt 0) {
            throw "Windows-child reconstruction failed and rollback was incomplete. Primary: $($primaryFailure.Message). Rollback: $($rollbackFailures -join '; ')"
        }
        throw $primaryFailure
    }
}

function Remove-VerifiedIncompleteCodexReplica {
    param(
        [string]$Root,
        [string]$Name
    )

    if ([string]::IsNullOrWhiteSpace($Name)) { throw '-ReplaceIncompleteReplica requires an explicit VMName.' }
    $rootFull = [IO.Path]::GetFullPath($Root).TrimEnd('\')
    $replicaFull = [IO.Path]::GetFullPath((Join-Path $rootFull $Name)).TrimEnd('\')
    if (
        $replicaFull.Equals($rootFull, [StringComparison]::OrdinalIgnoreCase) -or
        -not $replicaFull.StartsWith("${rootFull}\", [StringComparison]::OrdinalIgnoreCase)
    ) {
        throw "Refusing replacement outside the exact replica root: $replicaFull"
    }

    $vm = Get-VM -Name $Name -ErrorAction SilentlyContinue
    if ($null -eq $vm) { throw "Replacement target VM does not exist: $Name" }
    if ($vm.State -ne 'Off') { throw "Replacement target VM is not powered off: $Name" }
    if (@(Get-VMSnapshot -VMName $Name -ErrorAction SilentlyContinue).Count -ne 0) {
        throw "Replacement target has checkpoints and will not be removed: $Name"
    }
    if (-not (Test-Path -LiteralPath $replicaFull -PathType Container)) {
        throw "Replacement target directory does not exist: $replicaFull"
    }
    $replicaItem = Get-Item -LiteralPath $replicaFull -Force
    if (($replicaItem.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0) {
        throw "Replacement target is a reparse point and will not be removed: $replicaFull"
    }

    $manifestPath = Join-Path $replicaFull 'Replica-Manifest.json'
    if (-not (Test-Path -LiteralPath $manifestPath -PathType Leaf)) {
        throw "Replacement target has no validation manifest: $manifestPath"
    }
    try { $manifest = Get-Content -LiteralPath $manifestPath -Raw | ConvertFrom-Json }
    catch { throw "Replacement target manifest is unreadable: $($_.Exception.Message)" }
    $runtimeProperty = $manifest.PSObject.Properties['RuntimeVerification']
    if (
        [int]$manifest.SchemaVersion -ne 4 -or
        [string]$manifest.VMName -ne $Name -or
        -not [bool]$manifest.CodexDesktopReplica -or
        $null -eq $runtimeProperty -or
        $null -ne $runtimeProperty.Value
    ) {
        throw 'Replacement target is not the exact runtime-unverified Codex replica described by its schema-4 manifest.'
    }

    $expectedConfigurationLocation = [IO.Path]::GetFullPath((Join-Path (Join-Path $replicaFull 'VirtualMachine') $Name)).TrimEnd('\')
    $actualConfigurationLocation = [IO.Path]::GetFullPath([string]$vm.ConfigurationLocation).TrimEnd('\')
    if (-not $actualConfigurationLocation.Equals($expectedConfigurationLocation, [StringComparison]::OrdinalIgnoreCase)) {
        throw "Replacement VM configuration is outside the exact replica directory: $actualConfigurationLocation"
    }

    $disksRoot = [IO.Path]::GetFullPath((Join-Path $replicaFull 'Disks')).TrimEnd('\') + '\'
    $basesRoot = [IO.Path]::GetFullPath((Join-Path $replicaFull 'Bases')).TrimEnd('\') + '\'
    $attachedDrives = @(Get-VMHardDiskDrive -VMName $Name)
    if ($attachedDrives.Count -ne 3) { throw "Replacement target has $($attachedDrives.Count) attached disks instead of the exact three-disk Codex layout." }
    foreach ($drive in $attachedDrives) {
        $childPath = [IO.Path]::GetFullPath([string]$drive.Path)
        if (-not $childPath.StartsWith($disksRoot, [StringComparison]::OrdinalIgnoreCase) -or -not (Test-Path -LiteralPath $childPath -PathType Leaf)) {
            throw "Replacement target has a child disk outside its exact Disks directory: $childPath"
        }
        $vhd = Get-VHD -Path $childPath
        $parentPath = [IO.Path]::GetFullPath([string]$vhd.ParentPath)
        if ($vhd.VhdType -ne 'Differencing' -or -not $parentPath.StartsWith($basesRoot, [StringComparison]::OrdinalIgnoreCase) -or -not (Test-Path -LiteralPath $parentPath -PathType Leaf)) {
            throw "Replacement target has an unverified child/base chain: $childPath"
        }
    }

    Remove-VM -Name $Name -Force
    if ($null -ne (Get-VM -Name $Name -ErrorAction SilentlyContinue)) { throw "Failed to unregister incomplete VM $Name." }
    Remove-Item -LiteralPath $replicaFull -Recurse -Force
    if (Test-Path -LiteralPath $replicaFull) { throw "Failed to remove incomplete replica directory $replicaFull." }
    Write-ReplicaLog PASS "Removed only the exact powered-off, runtime-unverified replica $Name so its files cannot be embedded in the fresh C: image."
}

function Invoke-ExistingCodexReplicaAutoLogonVerification {
    param(
        [string]$Root,
        [string]$Name,
        [int]$BootTimeout,
        [int]$ValidationTimeout,
        [switch]$KeepConsoleClosed
    )

    if ([string]::IsNullOrWhiteSpace($Root)) { $Root = Join-Path $env:ProgramData 'Verified-Windows-Replicas' }
    $rootFull = [IO.Path]::GetFullPath($Root).TrimEnd('\')
    $replicaFull = [IO.Path]::GetFullPath((Join-Path $rootFull $Name)).TrimEnd('\')
    if ($replicaFull.Equals($rootFull, [StringComparison]::OrdinalIgnoreCase) -or -not $replicaFull.StartsWith("${rootFull}\", [StringComparison]::OrdinalIgnoreCase)) {
        throw "Existing-replica verification escaped the exact replica root: $replicaFull"
    }
    $manifestPath = Join-Path $replicaFull 'Replica-Manifest.json'
    if (-not (Test-Path -LiteralPath $manifestPath -PathType Leaf)) { throw "Existing replica manifest is missing: $manifestPath" }
    try { $manifest = Get-Content -LiteralPath $manifestPath -Raw | ConvertFrom-Json }
    catch { throw "Existing replica manifest is unreadable: $($_.Exception.Message)" }
    if (
        [int]$manifest.SchemaVersion -ne 4 -or
        [string]$manifest.VMName -ne $Name -or
        -not [bool]$manifest.CodexDesktopReplica -or
        $null -eq $manifest.RuntimeVerification -or
        $null -eq $manifest.CodexBaseline -or
        [string]$manifest.SourceComputerName -ne $env:COMPUTERNAME
    ) {
        throw 'The requested VM is not a complete schema-4 Codex replica of this exact computer.'
    }

    $vm = Get-VM -Name $Name -ErrorAction SilentlyContinue
    if ($null -eq $vm) { throw "Existing replica VM is not registered: $Name" }
    if ($vm.Generation -ne 2) { throw 'Existing replica is not a Generation 2 VM.' }
    if (@(Get-VMSnapshot -VMName $Name -ErrorAction SilentlyContinue).Count -ne 0) { throw 'Existing replica has checkpoints; refusing an ambiguous child-disk mutation.' }
    if ($vm.State -notin @('Running', 'Off')) { throw "Existing replica must be Running or Off, not $($vm.State)." }

    $matchingConsoles = @(Get-CimInstance Win32_Process -Filter "Name='vmconnect.exe'" -ErrorAction SilentlyContinue | Where-Object {
        -not [string]::IsNullOrWhiteSpace([string]$_.CommandLine) -and $_.CommandLine.IndexOf($Name, [StringComparison]::OrdinalIgnoreCase) -ge 0
    })
    foreach ($console in $matchingConsoles) {
        $consoleProcess = Get-Process -Id $console.ProcessId -ErrorAction SilentlyContinue
        if ($null -ne $consoleProcess) {
            [void]$consoleProcess.CloseMainWindow()
            if (-not $consoleProcess.WaitForExit(5000)) { Stop-Process -Id $console.ProcessId -Force -ErrorAction Stop }
        }
    }
    if ($matchingConsoles.Count -gt 0) { Write-ReplicaLog PASS "Closed $($matchingConsoles.Count) existing console instance(s) before hidden auto-logon verification." }

    [bool]$secretRetrieved = $false
    [int]$lsaError = 0
    [int]$logonError = 0
    $credentialValid = [ReplicaNativeMethods]::ValidateAutoLogonCredential(
        [string]$manifest.CodexBaseline.UserName,
        [string]$manifest.SourceComputerName,
        [ref]$secretRetrieved,
        [ref]$lsaError,
        [ref]$logonError
    )
    if (-not $secretRetrieved -or -not $credentialValid) {
        throw "The existing protected Admin auto-logon credential is not valid; no password prompt will be requested (LSA=$lsaError, LogonUser=$logonError)."
    }

    $guestCredential = $null
    $consoleOpened = $false
    try {
        $guestCredential = New-ReplicaGuestCredential -ComputerName ([string]$manifest.SourceComputerName) -UserName ([string]$manifest.CodexBaseline.UserName)
        if ($vm.State -eq 'Running') {
            $shutdownService = Get-VMIntegrationService -VMName $Name -Name Shutdown -ErrorAction Stop
            if (-not $shutdownService.Enabled -or $shutdownService.PrimaryStatusDescription -ne 'OK') {
                throw 'The Hyper-V Shutdown integration service is not healthy; refusing to power-cut the existing replica.'
            }
            Stop-VM -Name $Name -Confirm:$false -ErrorAction Stop
            $vm = Get-VM -Name $Name
            if ($vm.State -ne 'Off') { throw 'The existing replica did not complete its guest-OS shutdown.' }
            Write-ReplicaLog PASS 'The existing replica completed a graceful shutdown; its console remains closed.'
        }

        $windowsChild = [IO.Path]::GetFullPath([string]$manifest.VhdPaths.Windows.Child)
        $expectedChildRoot = [IO.Path]::GetFullPath((Join-Path $replicaFull 'Disks')).TrimEnd('\') + '\'
        if (-not $windowsChild.StartsWith($expectedChildRoot, [StringComparison]::OrdinalIgnoreCase) -or -not (Test-Path -LiteralPath $windowsChild -PathType Leaf)) {

        ) {
            throw 'The persisted actual post-VMConnect proof did not retain the unlocked credential-UI-free console state.'
        }
        Write-ReplicaLog PASS "Existing replica $Name stayed WTS-unlocked with zero credential-UI processes and Explorer present for 10 seconds after exactly one Basic Session VMConnect attached; the post-connect framebuffer and atomic manifest proof were persisted after the authenticated Codex UI gate."
    }
    catch {
        if ($consoleOpened) {
            $openedConsoles = @(Get-CimInstance Win32_Process -Filter "Name='vmconnect.exe'" -ErrorAction SilentlyContinue | Where-Object {
                -not [string]::IsNullOrWhiteSpace([string]$_.CommandLine) -and $_.CommandLine.IndexOf($Name, [StringComparison]::OrdinalIgnoreCase) -ge 0
            })
            foreach ($openedConsole in $openedConsoles) { Stop-Process -Id $openedConsole.ProcessId -Force -ErrorAction SilentlyContinue }
            $consoleOpened = $false
        }
        if (-not $consoleOpened) {
            $failedVm = Get-VM -Name $Name -ErrorAction SilentlyContinue
            if ($null -ne $failedVm -and $failedVm.State -eq 'Running') {
                $shutdownService = Get-VMIntegrationService -VMName $Name -Name Shutdown -ErrorAction SilentlyContinue
                if ($null -ne $shutdownService -and $shutdownService.Enabled -and $shutdownService.PrimaryStatusDescription -eq 'OK') {
                    Stop-VM -Name $Name -Confirm:$false -ErrorAction SilentlyContinue
                }
            }
        }
        throw
    }
    finally {
        if ($null -ne $guestCredential -and $null -ne $guestCredential.Password) { $guestCredential.Password.Dispose() }
    }

        MaximumCapturedShellBytes = [uint64]1GB
        Reused = $true
        BackingFileAutoExcludedFromMountedVhdBackup = $true
    }
    Write-ReplicaLog PASS "Reattached evidence for the exact existing isolated backup target at $Drive backed by $fullPath; a fresh offline audit must still prove and remove any captured pre-backup shell."

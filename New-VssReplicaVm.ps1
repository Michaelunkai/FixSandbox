function Test-WindowsVolume {
    param(
        [string]$WindowsVhd,
        [object]$CodexBaseline
    )

    $mounted = $false
    $access = $null
    try {
        $disk = Mount-VHD -Path $WindowsVhd -ReadOnly -Passthru
        $mounted = $true
        $candidates = @(Get-Partition -DiskNumber $disk.DiskNumber | Where-Object { $_.GptType -eq $basicDataGptType } | Sort-Object Size -Descending)
        if ($candidates.Count -lt 1) { throw 'Windows VHDX has no Basic Data partition.' }
        $partition = $candidates[0]
        $access = Add-TemporaryAccessPath -DiskNumber $disk.DiskNumber -PartitionNumber $partition.PartitionNumber
        $required = @(
            'Windows\System32\ntoskrnl.exe',
            'Windows\System32\winload.efi',
            'Windows\System32\config\SYSTEM',
            'Windows\System32\config\SOFTWARE',
            'Windows\System32\config\SAM',
            'Windows\System32\config\SECURITY',
            'Program Files',
            'Program Files (x86)',
            'ProgramData',
            'Users\Admin\NTUSER.DAT',
            'Users\Admin\Desktop'
        )
        $missing = @($required | Where-Object { -not (Test-Path -LiteralPath (Join-Path $access.Root $_)) })
        if ($missing.Count -gt 0) {
            throw "Windows VHDX is missing required paths: $($missing -join ', ')."
        }

        $hashes = foreach ($relativePath in @(
            'Windows\System32\ntoskrnl.exe',
            'Windows\System32\winload.efi',
            'Windows\System32\config\SYSTEM',
            'Windows\System32\config\SOFTWARE',
            'Windows\System32\config\SAM',
            'Windows\System32\config\SECURITY',
            'Users\Admin\NTUSER.DAT'
        )) {
            $item = Join-Path $access.Root $relativePath
            [pscustomobject]@{ Path = "C:\$relativePath"; SHA256 = (Get-FileHash -LiteralPath $item -Algorithm SHA256).Hash }
        }

        $shell = New-Object -ComObject WScript.Shell
        $shortcutRoots = @(
            (Join-Path $access.Root 'Users\Admin\Desktop'),
            (Join-Path $access.Root 'Users\Admin\AppData\Roaming\Microsoft\Windows\Start Menu'),
            (Join-Path $access.Root 'ProgramData\Microsoft\Windows\Start Menu')
        )
        $shortcuts = @(Get-ChildItem -LiteralPath $shortcutRoots -Filter '*.lnk' -File -Recurse -ErrorAction SilentlyContinue)
        $cTargetResults = foreach ($shortcut in $shortcuts) {
            $link = $shell.CreateShortcut($shortcut.FullName)
            if ($link.TargetPath -match '^C:\\') {
                $mappedTarget = Join-Path $access.Root $link.TargetPath.Substring(3)
                [pscustomobject]@{
                    Shortcut = $shortcut.FullName.Substring($access.Root.Length)
                    Target = $link.TargetPath
                    ReplicaTargetPresent = Test-Path -LiteralPath $mappedTarget
                    HostTargetPresent = Test-Path -LiteralPath $link.TargetPath
                }
            }
        }
        $parityFailures = @($cTargetResults | Where-Object { $_.ReplicaTargetPresent -ne $_.HostTargetPresent })
        if ($parityFailures.Count -gt 0 -and -not $ReuseLatestBackup) {
            throw "$($parityFailures.Count) C: shortcut target(s) differ between the new backup and the live host."
        }

        $codexAudit = if ($null -ne $CodexBaseline) {
            Test-OfflineCodexState -WindowsRoot $access.Root -Baseline $CodexBaseline
        }
        else { $null }

        Write-ReplicaLog PASS "Windows VHDX contains the OS, registry, Admin profile, application roots, and $($shortcuts.Count) shortcut files; C: target parity differences=$($parityFailures.Count)."
        return [pscustomobject]@{
            CoreHashes = @($hashes)
            ShortcutCount = $shortcuts.Count
            CTargetCount = @($cTargetResults).Count
            CTargetParityDifferenceCount = $parityFailures.Count
            CTargetParityDifferences = @($parityFailures)
            CodexAudit = $codexAudit
        }
    }
    finally {
        if ($mounted) {
            if ($null -ne $access -and $access.Added) {
                Remove-PartitionAccessPath -DiskNumber $disk.DiskNumber -PartitionNumber $partition.PartitionNumber -AccessPath $access.Root -ErrorAction SilentlyContinue
            }
            Dismount-VHD -Path $WindowsVhd -ErrorAction SilentlyContinue
        }
    }
}

function Get-FixedDataDiskPlans {
    $systemPartition = Get-Partition -DriveLetter $env:SystemDrive.TrimEnd(':')
    $fixedVolumes = @(Get-Volume | Where-Object { $_.DriveType -eq 'Fixed' -and $_.DriveLetter })
    $dataVolumes = @($fixedVolumes | Where-Object { [string]$_.DriveLetter -ne $env:SystemDrive.TrimEnd(':') })
    $plans = [System.Collections.Generic.List[object]]::new()

    foreach ($diskNumber in @($dataVolumes | ForEach-Object { (Get-Partition -DriveLetter $_.DriveLetter).DiskNumber } | Sort-Object -Unique)) {
        if ($diskNumber -eq $systemPartition.DiskNumber) {
            throw "A non-system drive letter unexpectedly resides on the Windows disk $diskNumber."
        }
        $disk = Get-Disk -Number $diskNumber
        if ($disk.IsBoot -or $disk.IsSystem) { throw "Refusing to data-clone boot/system disk $diskNumber."
        }
        if ($disk.PartitionStyle -ne 'MBR') {
            throw "Fixed data disk $diskNumber uses $($disk.PartitionStyle); this script requires MBR data disks so their exact signature-based drive-letter identities can be reproduced."
        }
        $volumes = [System.Collections.Generic.List[object]]::new()
        foreach ($volume in @($dataVolumes | Where-Object { (Get-Partition -DriveLetter $_.DriveLetter).DiskNumber -eq $diskNumber } | Sort-Object DriveLetter)) {
            $partition = Get-Partition -DriveLetter $volume.DriveLetter
            if ($volume.FileSystem -notin @('NTFS', 'exFAT', 'FAT', 'FAT32')) {
                throw "Unsupported filesystem $($volume.FileSystem) on $($volume.DriveLetter):."
            }
            $volumes.Add([pscustomobject]@{
                DriveLetter = [string]$volume.DriveLetter
                PartitionNumber = $partition.PartitionNumber
                Offset = [uint64]$partition.Offset
                Size = [uint64]$partition.Size
                MbrType = [byte]$partition.MbrType
                IsActive = [bool]$partition.IsActive
                FileSystem = [string]$volume.FileSystem
                FileSystemLabel = [string]$volume.FileSystemLabel
                AllocationUnitSize = [uint32]$volume.AllocationUnitSize
                UsedBytes = [uint64]($volume.Size - $volume.SizeRemaining)
            })
        }

        $allPartitions = @(Get-Partition -DiskNumber $diskNumber)
        $unrepresented = @($allPartitions | Where-Object { $_.Size -gt 0 -and $_.PartitionNumber -notin @($volumes.PartitionNumber) })
        if ($unrepresented.Count -gt 0) {
            throw "Data disk $diskNumber has $($unrepresented.Count) partition(s) without fixed drive letters; refusing to claim complete coverage."
        }
        $plans.Add([pscustomobject]@{
            DiskNumber = $diskNumber
            FriendlyName = [string]$disk.FriendlyName
            Size = [uint64]$disk.Size
            Signature = [uint32]$disk.Signature
            LogicalSectorSize = [uint32]$disk.LogicalSectorSize
            PhysicalSectorSize = [uint32]$disk.PhysicalSectorSize
            Volumes = @($volumes)
        })
    }
    return @($plans)
}

function Test-SourceDriveLetterMappings {
    param([object[]]$Plans)

    $registry = [Microsoft.Win32.RegistryKey]::OpenBaseKey(
        [Microsoft.Win32.RegistryHive]::LocalMachine,
        [Microsoft.Win32.RegistryView]::Default
    )
    $key = $null
    try {
        $key = $registry.OpenSubKey('SYSTEM\MountedDevices', $false)
        if ($null -eq $key) { throw 'HKLM\SYSTEM\MountedDevices is unavailable.' }
        $results = foreach ($plan in $Plans) {
            foreach ($volume in $plan.Volumes) {
                $name = "\DosDevices\$($volume.DriveLetter):"
                $actual = [byte[]]$key.GetValue($name, $null, [Microsoft.Win32.RegistryValueOptions]::DoNotExpandEnvironmentNames)
                $expected = [byte[]](@([BitConverter]::GetBytes([uint32]$plan.Signature)) + @([BitConverter]::GetBytes([uint64]$volume.Offset)))
                $actualHex = if ($null -eq $actual) { '' } else { [BitConverter]::ToString($actual).Replace('-', '') }
                $expectedHex = [BitConverter]::ToString($expected).Replace('-', '')
                if ($actualHex -ne $expectedHex) {
                    throw "MountedDevices mapping for $($volume.DriveLetter): does not match disk signature $($plan.Signature) and offset $($volume.Offset)."
                }
                [pscustomobject]@{ DriveLetter = "$($volume.DriveLetter):"; RegistryValue = $actualHex; Verified = $true }
            }
        }
        Write-ReplicaLog PASS "Verified $(@($results).Count) source MountedDevices mappings for fixed data volumes."
        return @($results)
    }
    finally {
        if ($null -ne $key) { $key.Dispose() }
        $registry.Dispose()
    }
}

function New-DataVolumeShadow {
    param([string]$DriveLetter)

    $result = $null
    for ($attempt = 1; $attempt -le 60; $attempt++) {
        $result = Invoke-CimMethod -ClassName Win32_ShadowCopy -MethodName Create -Arguments @{
            Volume = "${DriveLetter}:\"
            Context = 'ClientAccessible'
        }
        if ($result.ReturnValue -eq 0) { break }
        if ($result.ReturnValue -ne 9) {
            throw "VSS failed to create a data snapshot for ${DriveLetter}: (return value $($result.ReturnValue))."
        }
        if ($attempt -eq 6 -and -not (Get-Process wbadmin -ErrorAction SilentlyContinue)) {
            Write-ReplicaLog WARN "VSS still reports another snapshot operation after 30 seconds; refreshing only VSS and its provider."
            Stop-Service -Name swprv -Force -ErrorAction SilentlyContinue
            Stop-Service -Name VSS -Force -ErrorAction SilentlyContinue
            Start-Service -Name VSS
            Start-Service -Name swprv
        }
        if ($attempt -lt 60) {
            if ($attempt -eq 1) { Write-ReplicaLog INFO "Waiting for the preceding Windows Backup snapshot operation to release VSS."
            }
            Start-Sleep -Seconds 5
        }
    }
    if ($result.ReturnValue -ne 0 -or [string]::IsNullOrWhiteSpace([string]$result.ShadowID)) {
        throw "VSS failed to create a data snapshot for ${DriveLetter}: (return value $($result.ReturnValue))."
    }
    $shadow = Get-CimInstance -ClassName Win32_ShadowCopy -Filter "ID='$($result.ShadowID)'"
    if ($null -eq $shadow -or [string]::IsNullOrWhiteSpace([string]$shadow.DeviceObject)) {
        throw "VSS created $($result.ShadowID), but its device path is unavailable."
    }
    $temporaryLetter = Get-FreeDriveLetter
    $deviceName = "${temporaryLetter}:"
    $root = "${temporaryLetter}:\"
    $nativeTarget = ([string]$shadow.DeviceObject).Replace('\\?\GLOBALROOT', '')
    if (-not $nativeTarget.StartsWith('\Device\HarddiskVolumeShadowCopy', [StringComparison]::OrdinalIgnoreCase)) {
        $wmiShadow = Get-WmiObject -Class Win32_ShadowCopy -Filter "ID='$($shadow.ID)'" -ErrorAction SilentlyContinue
        if ($null -ne $wmiShadow) { $null = $wmiShadow.Delete() }
        throw "VSS returned an unexpected device path: $($shadow.DeviceObject)"
    }
    $mapped = $false
    try {
        $mapped = [ReplicaNativeMethods]::DefineDosDevice(1, $deviceName, $nativeTarget)
        if (-not $mapped) {
            throw "DefineDosDevice could not map VSS snapshot $($shadow.ID) (Win32 $([Runtime.InteropServices.Marshal]::GetLastWin32Error()))."
        }
        if (-not (Test-Path -LiteralPath $root -PathType Container)) {
            throw "The temporary VSS drive $deviceName is not readable."
        }
        $rootItem = Get-Item -LiteralPath $root -Force
        if (($rootItem.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0) {
            throw "The temporary VSS source $root unexpectedly resolves as a reparse point."
        }
    }
    catch {
        if ($mapped) {
            $null = [ReplicaNativeMethods]::DefineDosDevice(7, $deviceName, $nativeTarget)
        }
        $wmiShadow = Get-WmiObject -Class Win32_ShadowCopy -Filter "ID='$($shadow.ID)'" -ErrorAction SilentlyContinue
        if ($null -ne $wmiShadow) { $null = $wmiShadow.Delete() }
        throw
    }
    Write-ReplicaLog PASS "Created immutable VSS source for ${DriveLetter}: and mapped it directly as $deviceName."
    return [pscustomobject]@{
        ID = [string]$shadow.ID
        DeviceObject = [string]$shadow.DeviceObject
        DeviceName = $deviceName
        NativeTarget = $nativeTarget
        Root = $root
    }
}

function Remove-DataVolumeShadow {
    param([object]$Shadow)

    if ($null -ne $Shadow) {
        $shadowId = [string]$Shadow.ID
        $mappingFailure = $null
        if ($Shadow.DeviceName) {
            $deviceName = [string]$Shadow.DeviceName
            $nativeTarget = [string]$Shadow.NativeTarget
            for ($attempt = 1; $attempt -le 16; $attempt++) {
                $currentTarget = Get-DosDeviceTarget -DeviceName $deviceName
                if ([string]::IsNullOrWhiteSpace($currentTarget) -or $currentTarget -ne $nativeTarget) { break }
                $removed = [ReplicaNativeMethods]::DefineDosDevice(7, $deviceName, $nativeTarget)
                if (-not $removed) {
                    $win32Error = [Runtime.InteropServices.Marshal]::GetLastWin32Error()
                    $mappingFailure = "Could not remove temporary VSS drive $deviceName (Win32 $win32Error)."
                    break
                }
            }
            if ((Get-DosDeviceTarget -DeviceName $deviceName) -eq $nativeTarget) {
                $mappingFailure = "Temporary VSS drive $deviceName still maps to $nativeTarget after cleanup."
            }
        }
        $wmiShadow = Get-WmiObject -Class Win32_ShadowCopy -Filter "ID='$shadowId'" -ErrorAction SilentlyContinue
        if ($null -ne $wmiShadow) { $null = $wmiShadow.Delete() }
        if (Get-CimInstance -ClassName Win32_ShadowCopy -Filter "ID='$shadowId'" -ErrorAction SilentlyContinue) {
            Write-ReplicaLog WARN "Could not confirm deletion of VSS snapshot $shadowId."
        }
        else {
            Write-ReplicaLog PASS "Removed temporary VSS snapshot $shadowId."
        }
        if ($mappingFailure) { throw $mappingFailure }
    }
}

function Restore-ReplicaStorageMaintenance {
    param([object]$State)

    if ($null -eq $State) { return }

    $startupType = switch ([string]$State.ServiceStartMode) {
        'Auto' { 'Automatic' }
        'Manual' { 'Manual' }
        'Disabled' { 'Disabled' }
        default { throw "Unsupported saved defragsvc start mode: $($State.ServiceStartMode)" }
    }
    Set-Service -Name defragsvc -StartupType $startupType -ErrorAction Stop
    if ($State.ServiceWasRunning) {
        Start-Service -Name defragsvc -ErrorAction Stop
    }
    else {
        Stop-Service -Name defragsvc -Force -ErrorAction SilentlyContinue
    }

    if ($State.TaskWasEnabled) {
        Enable-ScheduledTask -TaskPath '\Microsoft\Windows\Defrag\' -TaskName 'ScheduledDefrag' -ErrorAction Stop | Out-Null
    }
    else {
        Disable-ScheduledTask -TaskPath '\Microsoft\Windows\Defrag\' -TaskName 'ScheduledDefrag' -ErrorAction Stop | Out-Null
    }

    $restoredService = Get-CimInstance -ClassName Win32_Service -Filter "Name='defragsvc'" -ErrorAction Stop
    $restoredTask = Get-ScheduledTask -TaskPath '\Microsoft\Windows\Defrag\' -TaskName 'ScheduledDefrag' -ErrorAction Stop
    if ([string]$restoredService.StartMode -ne [string]$State.ServiceStartMode) {
        throw "Storage Optimizer service start mode was not restored to $($State.ServiceStartMode)."
    }
    if ([bool]$restoredTask.Settings.Enabled -ne [bool]$State.TaskWasEnabled) {
        throw 'ScheduledDefrag enabled state was not restored.'
    }
    Write-ReplicaLog PASS 'Restored the original Storage Optimizer service and ScheduledDefrag states.'
}

function Suspend-ReplicaStorageMaintenance {
    $service = Get-CimInstance -ClassName Win32_Service -Filter "Name='defragsvc'" -ErrorAction Stop
    $task = Get-ScheduledTask -TaskPath '\Microsoft\Windows\Defrag\' -TaskName 'ScheduledDefrag' -ErrorAction Stop
    $state = [pscustomobject]@{
        ServiceStartMode = [string]$service.StartMode
        ServiceWasRunning = ([string]$service.State -eq 'Running')
        TaskWasEnabled = [bool]$task.Settings.Enabled
    }

    try {
        Disable-ScheduledTask -TaskPath '\Microsoft\Windows\Defrag\' -TaskName 'ScheduledDefrag' -ErrorAction Stop | Out-Null
        Stop-Service -Name defragsvc -Force -ErrorAction Stop
        Set-Service -Name defragsvc -StartupType Disabled -ErrorAction Stop

        $guardedService = Get-CimInstance -ClassName Win32_Service -Filter "Name='defragsvc'" -ErrorAction Stop
        $guardedTask = Get-ScheduledTask -TaskPath '\Microsoft\Windows\Defrag\' -TaskName 'ScheduledDefrag' -ErrorAction Stop
        if ([string]$guardedService.State -ne 'Stopped' -or [string]$guardedService.StartMode -ne 'Disabled') {
            throw 'Storage Optimizer service did not enter the required stopped/disabled state.'
        }
        if ([bool]$guardedTask.Settings.Enabled) {
            throw 'ScheduledDefrag did not enter the required disabled state.'
        }
        Write-ReplicaLog PASS 'Suspended Storage Optimizer and ScheduledDefrag for the storage-intensive replica phase.'
        return $state
    }
    catch {
        try { Restore-ReplicaStorageMaintenance -State $state }
        catch { Write-ReplicaLog WARN "Storage-maintenance rollback also failed: $($_.Exception.Message)" }
        throw
    }
}

function Set-MbrPartitionIdWithDiskPart {
    param(
        [int]$DiskNumber,
        [int]$PartitionNumber,
        [byte]$MbrType
    )

    $inputText = "select disk $DiskNumber`r`nselect partition $PartitionNumber`r`nset id=$($MbrType.ToString('X2')) override`r`nexit`r`n"
    $startInfo = [Diagnostics.ProcessStartInfo]::new()
    $startInfo.FileName = Join-Path $env:WINDIR 'System32\diskpart.exe'
    $startInfo.UseShellExecute = $false
    $startInfo.RedirectStandardInput = $true
    $startInfo.RedirectStandardOutput = $true
    $startInfo.RedirectStandardError = $true
    $startInfo.CreateNoWindow = $true
    $process = [Diagnostics.Process]::Start($startInfo)
    try {
        $process.StandardInput.Write($inputText)
        $process.StandardInput.Close()
        $output = $process.StandardOutput.ReadToEnd()
        $errorText = $process.StandardError.ReadToEnd()
        $process.WaitForExit()
        if ($process.ExitCode -ne 0 -or $output -notmatch 'successfully set the partition ID') {
            throw "DiskPart could not set MBR type 0x$($MbrType.ToString('X2')) on disk $DiskNumber partition $PartitionNumber. $errorText $output"
        }
    }
    finally {
        $process.Dispose()
    }
}

function Test-RobocopyMirrorEvidence {
    param(

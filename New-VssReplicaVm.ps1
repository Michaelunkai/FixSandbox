        $finalVm = Get-VM -Name $VMName
        if ($finalVm.State -ne 'Running') { throw 'The VM stopped after runtime proof and before console release.' }
        $finalKvp = Get-GuestKvp -VM $finalVm -Custom
        $finalStatusProperty = $finalKvp.PSObject.Properties['CodexReplicaStatus']
        if ($null -eq $finalStatusProperty -or [string]$finalStatusProperty.Value -ne "PASS:$($codexVerifier.ValidationId)") {
            throw 'The guest no longer exposes the nonce-bound PASS immediately before console release.'
        }
        $finalGuestEvidence = Get-CodexGuestEvidenceViaPowerShellDirect -Name $VMName -Credential $guestCredential
        Assert-CodexGuestEvidence -Evidence $finalGuestEvidence -ExpectedValidationId $codexVerifier.ValidationId -Baseline $codexBaseline
        if ([string]$finalGuestEvidence.EvidenceSha256 -ne [string]$persistedManifest.RuntimeVerification.Codex.EvidenceSha256) {
            throw 'The final PowerShell Direct evidence hash changed after manifest persistence.'
        }
        [void](Get-ProtectedBackupRetentionEvidence -Backup $backup -ArchiveParent $protectedArchiveParent -Expected $protectedBackupRetentionBaseline)
        [void](Get-BasicVmConnectSessionEvidence -Name $VMName -TimeoutSeconds 10)
        Write-ReplicaLog PASS 'Final release gate passed: the VM cold-booted through persistent password-prompt-free Admin auto-logon into an interactive Explorer/Codex desktop, Enhanced Session Mode is unavailable so VMConnect must expose that already-authenticated basic console, its nonce-bound KVP PASS and credential-authenticated PowerShell Direct evidence are still live, the persisted manifest is complete, and the protected Windows Backup remains intact.'

        $vmConnect = Join-Path $env:WINDIR 'System32\vmconnect.exe'
        if (Test-Path -LiteralPath $vmConnect) {
            Start-Process -FilePath $vmConnect -ArgumentList @('localhost', $VMName)
            $consoleOpened = $true
            $consoleDeadline = (Get-Date).AddSeconds(15)
            do {
                Start-Sleep -Milliseconds 500
                $releasedConsoles = @(Get-CimInstance Win32_Process -Filter "Name='vmconnect.exe'" -ErrorAction SilentlyContinue | Where-Object {
                    -not [string]::IsNullOrWhiteSpace([string]$_.CommandLine) -and $_.CommandLine.IndexOf($VMName, [StringComparison]::OrdinalIgnoreCase) -ge 0
                })
            } while ($releasedConsoles.Count -ne 1 -and (Get-Date) -lt $consoleDeadline)
            if ($releasedConsoles.Count -ne 1) { throw "Console release produced $($releasedConsoles.Count) matching VMConnect processes instead of exactly one." }
            [void](Get-BasicVmConnectSessionEvidence -Name $VMName -TimeoutSeconds 10)
            Start-Sleep -Seconds 10
            $postConnectFramebuffer = Save-VMConsoleFramebufferProof -Name $VMName -Path (Join-Path $replicaPath 'PostConnect-Console-Framebuffer-Proof.png') -ExpectedVmConnectProcessCount 1
            $postConnectGuest = Get-GuestUnlockedConsoleEvidence -Name $VMName -Credential $guestCredential
            $persistedManifest = Set-PostConnectProofInManifest -ManifestPath $manifestPath -GuestEvidence $postConnectGuest -FramebufferEvidence $postConnectFramebuffer
            Write-ReplicaLog PASS "Opened $VMName only after permanent no-lock policy; its actual post-connect state stayed WTS-unlocked with zero credential-UI processes and Explorer present, and its post-connect framebuffer proof was persisted after the authenticated Codex UI gate."
        }
    }
    catch {
        if ($CodexDesktopReplica) {
            if ($consoleOpened) {
                $openedConsoles = @(Get-CimInstance Win32_Process -Filter "Name='vmconnect.exe'" -ErrorAction SilentlyContinue | Where-Object {
                    -not [string]::IsNullOrWhiteSpace([string]$_.CommandLine) -and $_.CommandLine.IndexOf($VMName, [StringComparison]::OrdinalIgnoreCase) -ge 0
                })
                foreach ($openedConsole in $openedConsoles) { Stop-Process -Id $openedConsole.ProcessId -Force -ErrorAction SilentlyContinue }
                $consoleOpened = $false
            }
            $failedVm = Get-VM -Name $VMName -ErrorAction SilentlyContinue
            if ($null -ne $failedVm -and $failedVm.State -ne 'Off') {
                $gracefulFailureShutdown = $false
                $shutdownService = Get-VMIntegrationService -VMName $VMName -Name Shutdown -ErrorAction SilentlyContinue
                if ($null -ne $shutdownService -and $shutdownService.Enabled -and $shutdownService.PrimaryStatusDescription -eq 'OK') {
                    try {
                        Stop-VM -Name $VMName -Confirm:$false -ErrorAction Stop
                        $gracefulFailureShutdown = ((Get-VM -Name $VMName).State -eq 'Off')
                    }
                    catch { $gracefulFailureShutdown = $false }
                }
                if (-not $gracefulFailureShutdown) {
                    Stop-VM -Name $VMName -TurnOff -Force -ErrorAction SilentlyContinue
                    Write-ReplicaLog WARN 'Codex validation failed; a healthy guest shutdown channel was unavailable, so the guest was powered off fail-closed and its console was never opened.'
                }
                else {
                    Write-ReplicaLog WARN 'Codex validation failed; the guest completed a graceful operating-system shutdown and its console was never opened.'
                }
            }
        }
        throw
    }
    finally {
        if ($null -ne $guestCredential -and $null -ne $guestCredential.Password) {
            $guestCredential.Password.Dispose()
            $guestCredential = $null
        }
    }
}
else {
    Write-ReplicaLog PASS "Created and fully validated $VMName offline; -NoLaunch kept it powered off."
}

$elapsed = [math]::Round(((Get-Date) - $startedAt).TotalSeconds, 1)
Write-ReplicaLog PASS "VSS replica workflow completed in ${elapsed}s. Manifest=$manifestPath"
}
finally {
    if ($null -ne $maintenanceState) {
        Restore-ReplicaStorageMaintenance -State $maintenanceState
    }
    if ($null -ne $backupServiceState) {
        Restore-ReplicaServiceState -State $backupServiceState
    }
}

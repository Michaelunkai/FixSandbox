            throw 'Atomic offline SYSTEM hive replacement did not retain the verified content.'
        }
        Remove-Item -LiteralPath $backupHive -Force -ErrorAction Stop
        return $controlSetCount
    }
    catch {
        $primaryFailure = $_.Exception
        if (Test-Path -LiteralPath $backupHive -PathType Leaf) {
            try {
                [IO.File]::Replace($backupHive, $systemHiveFull, $null, $true)
            }
            catch {
                $rollbackFailed = $true
                throw "Offline SYSTEM hive update failed and its atomic rollback also failed. Original error: $($primaryFailure.Message). Rollback error: $($_.Exception.Message)"
            }
        }
        throw $primaryFailure
    }
    finally {
        if (Test-Path -LiteralPath $newHive -PathType Leaf) { Remove-Item -LiteralPath $newHive -Force -ErrorAction SilentlyContinue }
        if (-not $rollbackFailed -and (Test-Path -LiteralPath $backupHive -PathType Leaf)) { Remove-Item -LiteralPath $backupHive -Force -ErrorAction SilentlyContinue }
    }
}

function Set-OfflinePersistentAutoLogon {
    param(
        [string]$SoftwareHivePath,
        [string]$UserName,
        [string]$ComputerName
    )

    if ([string]::IsNullOrWhiteSpace($UserName) -or [string]::IsNullOrWhiteSpace($ComputerName)) {
        throw 'Persistent automatic logon requires non-empty user and computer names.'
    }
    if ($null -eq ('CodexReplicaOfflineRegistry' -as [type])) {
        throw 'The verified Microsoft Offline Registry helper was not initialized before automatic-logon preparation.'
    }

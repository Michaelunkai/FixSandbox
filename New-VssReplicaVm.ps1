function Write-ReplicaLog {
    param(
        [ValidateSet('INFO', 'PASS', 'WARN')]
        [string]$Level,
        [string]$Message
    )

    $line = '{0:u} [{1}] {2}' -f (Get-Date), $Level, $Message

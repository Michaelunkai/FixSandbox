            'Automatic' { 'Automatic' }
            'Manual' { 'Manual' }
            'Disabled' { 'Disabled' }
            default { throw "Unsupported saved startup type for $($record.Name): $($record.StartType)" }
        }
        if ($record.Status -eq 'Running') {
            if ((Get-Service -Name $record.Name).StartType -eq [System.ServiceProcess.ServiceStartMode]::Disabled) {
                Set-Service -Name $record.Name -StartupType Manual
            }
            if ((Get-Service -Name $record.Name).Status -ne 'Running') { Start-Service -Name $record.Name }
            Set-Service -Name $record.Name -StartupType $startupType
        }
        else {
            if ((Get-Service -Name $record.Name).Status -ne 'Stopped') {
                Stop-Service -Name $record.Name -Force -ErrorAction SilentlyContinue
                (Get-Service -Name $record.Name).WaitForStatus([System.ServiceProcess.ServiceControllerStatus]::Stopped, [TimeSpan]::FromSeconds(30))
            }
            Set-Service -Name $record.Name -StartupType $startupType
        }
    }
    Write-ReplicaLog PASS 'Restored VSS/Windows Backup services to their exact pre-run startup and running states.'
}

function Initialize-StorageManagement {
    foreach ($serviceName in @('StorSvc', 'smphost', 'vds')) {
        $service = Get-Service -Name $serviceName -ErrorAction SilentlyContinue
        if ($null -eq $service) { continue }
        if ($service.StartType -eq [System.ServiceProcess.ServiceStartMode]::Disabled) {
            Set-Service -Name $serviceName -StartupType Manual
        }
        if ((Get-Service -Name $serviceName).Status -ne 'Running') { Start-Service -Name $serviceName }
    }
    Update-HostStorageCache
    $disks = @(Get-Disk)
    if ($disks.Count -eq 0) {
        Write-ReplicaLog WARN 'The Storage CIM provider returned no disks; restarting its service chain once.'
        foreach ($serviceName in @('smphost', 'vds', 'StorSvc')) {
            $service = Get-Service -Name $serviceName -ErrorAction SilentlyContinue
            if ($null -ne $service -and $service.Status -eq 'Running') { Restart-Service -Name $serviceName -Force }
        }
        Start-Sleep -Seconds 5
        Update-HostStorageCache
        $disks = @(Get-Disk)
    }
    if ($disks.Count -eq 0) { throw 'The Storage CIM provider is running but returned no physical disks.' }
    Write-ReplicaLog PASS "Storage management is healthy and reports $($disks.Count) physical disk(s)."
}

function Get-DosDeviceTarget {
    param([string]$DeviceName)

    $buffer = New-Object Text.StringBuilder 4096
    $length = [ReplicaNativeMethods]::QueryDosDevice($DeviceName, $buffer, $buffer.Capacity)
    if ($length -eq 0) { return $null }
    return [string]($buffer.ToString().Split([char]0)[0])
}

function Get-FreeDriveLetter {
    foreach ($codePoint in 82..68) {
        $letter = [char]$codePoint
        $deviceName = "${letter}:"
        if (-not (Test-Path ("{0}:\" -f $letter)) -and $null -eq (Get-DosDeviceTarget -DeviceName $deviceName)) {
            return [string]$letter
        }
    }
    throw 'No free temporary drive letter is available.'
}

function Get-ByteArraySha256 {
    param([byte[]]$Bytes)

    $algorithm = [Security.Cryptography.SHA256]::Create()
    try {
        return ([BitConverter]::ToString($algorithm.ComputeHash($Bytes))).Replace('-', '')
    }
    finally {
        $algorithm.Dispose()
    }
}

function Get-DirectoryFileEvidence {
    param([string]$Path)

    if (-not (Test-Path -LiteralPath $Path -PathType Container)) {
        throw "Required directory is missing: $Path"
    }
    $files = @(Get-ChildItem -LiteralPath $Path -Force -File -Recurse -ErrorAction Stop)
    return [pscustomobject]@{
        FileCount = $files.Count
        Bytes = [uint64](($files | Measure-Object Length -Sum).Sum)
        NewestWriteUtc = if ($files.Count -gt 0) {
            ($files | Sort-Object LastWriteTimeUtc -Descending | Select-Object -First 1).LastWriteTimeUtc.ToString('o')
        }
        else { $null }
    }
}

function Get-SystemRelativePath {
    param([string]$Path)

    $systemRoot = [IO.Path]::GetFullPath("$($env:SystemDrive)\")
    $fullPath = [IO.Path]::GetFullPath($Path)
    if (-not $fullPath.StartsWith($systemRoot, [StringComparison]::OrdinalIgnoreCase)) {
        throw "Codex path is not on the Windows volume: $fullPath"
    }
    return $fullPath.Substring($systemRoot.Length)
}

function Get-KernelCatalogTrustEvidence {
    $catalogSetId = '{F750E6C3-38EE-11D1-85E5-00C04FC295EE}'
    $catRoot = Join-Path $env:WINDIR "System32\CatRoot\$catalogSetId"
    $catRoot2 = Join-Path $env:WINDIR "System32\CatRoot2\$catalogSetId"
    if (-not (Test-Path -LiteralPath $catRoot -PathType Container)) {
        throw "Windows kernel catalog directory is missing: $catRoot"
    }
    if (-not (Test-Path -LiteralPath $catRoot2 -PathType Container)) {
        throw "Windows kernel catalog database directory is missing: $catRoot2"
    }

    $catalogFiles = @(Get-ChildItem -LiteralPath $catRoot -Filter '*.cat' -File -ErrorAction Stop)
    $catalogDatabaseFiles = @(Get-ChildItem -LiteralPath $catRoot2 -File -Recurse -ErrorAction Stop)
    if ($catalogFiles.Count -eq 0 -or $catalogDatabaseFiles.Count -eq 0) {
        throw 'Windows kernel catalog store is empty; a clone could fail boot with CRITICAL_SERVICE_FAILED/0xc0000428.'
    }

    $signatureToolCandidates = @(
        (Join-Path ${env:ProgramFiles(x86)} 'Windows Kits\10\Tools\bin\i386\signtool.exe'),
        (Join-Path ${env:ProgramFiles(x86)} 'Windows Kits\10\App Certification Kit\signtool.exe')
    )
    $signatureTool = $signatureToolCandidates |
        Where-Object { -not [string]::IsNullOrWhiteSpace($_) -and (Test-Path -LiteralPath $_ -PathType Leaf) } |
        Select-Object -First 1
    if ([string]::IsNullOrWhiteSpace([string]$signatureTool)) {
        throw 'A local Microsoft signtool.exe is required for kernel-policy validation.'
    }

    $criticalRelativePaths = @(
        'Windows\System32\drivers\filecrypt.sys',
        'Windows\System32\drivers\acpi.sys',
        'Windows\System32\drivers\vmbus.sys',
        'Windows\System32\drivers\storvsc.sys',
        'Windows\System32\drivers\volmgr.sys',
        'Windows\System32\drivers\volmgrx.sys',
        'Windows\System32\drivers\disk.sys',
        'Windows\System32\drivers\classpnp.sys',
        'Windows\System32\drivers\mountmgr.sys',
        'Windows\System32\drivers\partmgr.sys',
        'Windows\System32\drivers\fltmgr.sys',
        'Windows\System32\drivers\ntfs.sys',
        'Windows\System32\drivers\fvevol.sys',
        'Windows\System32\drivers\spaceport.sys',
        'Windows\System32\drivers\stornvme.sys',
        'Windows\System32\drivers\pci.sys',
        'Windows\System32\ci.dll',
        'Windows\System32\winload.efi'
    )
    $criticalChecks = foreach ($relativePath in $criticalRelativePaths) {
        $fullPath = Join-Path "$($env:SystemDrive)\" $relativePath
        if (-not (Test-Path -LiteralPath $fullPath -PathType Leaf)) {
            throw "Critical Windows boot/signature file is missing: $fullPath"
        }
        $savedErrorActionPreference = $ErrorActionPreference
        try {
            $ErrorActionPreference = 'Continue'
            $signatureOutput = @(& $signatureTool verify /kp /a /q $fullPath 2>&1)
            $signatureExitCode = $LASTEXITCODE
        }
        finally { $ErrorActionPreference = $savedErrorActionPreference }
        if ($signatureExitCode -ne 0) {
            throw "Kernel-policy signature verification failed for $fullPath (signtool exit $signatureExitCode)."
        }
        [pscustomobject]@{
            RelativePath = $relativePath
            Sha256 = (Get-FileHash -LiteralPath $fullPath -Algorithm SHA256).Hash
        }
    }

    $fileCryptPath = Join-Path "$($env:SystemDrive)\" 'Windows\System32\drivers\filecrypt.sys'
    $savedErrorActionPreference = $ErrorActionPreference
    try {
        $ErrorActionPreference = 'Continue'
        $verboseOutput = @(& $signatureTool verify /kp /a /v $fileCryptPath 2>&1)
        $verboseExitCode = $LASTEXITCODE
    }
    finally { $ErrorActionPreference = $savedErrorActionPreference }
    if ($verboseExitCode -ne 0) { throw 'Verbose kernel-policy verification failed for filecrypt.sys.' }
    $catalogLine = $verboseOutput | Where-Object { [string]$_ -match 'File is signed in catalog:\s*(.+?)\s*$' } | Select-Object -First 1
    if ($null -eq $catalogLine) { throw 'signtool did not identify the installed catalog used by filecrypt.sys.' }
    $catalogPath = ([regex]::Match([string]$catalogLine, 'File is signed in catalog:\s*(.+?)\s*$').Groups[1].Value).Trim().Trim('"')
    $catalogRootFull = [IO.Path]::GetFullPath($catRoot).TrimEnd('\')
    $catalogPathFull = [IO.Path]::GetFullPath($catalogPath)
    if (
        -not $catalogPathFull.StartsWith("${catalogRootFull}\", [StringComparison]::OrdinalIgnoreCase) -or
        -not (Test-Path -LiteralPath $catalogPathFull -PathType Leaf)
    ) {
        throw "filecrypt.sys resolved to an untrusted or missing catalog path: $catalogPathFull"
    }

    $evidence = [pscustomobject]@{
        CatalogSetId = $catalogSetId
        CatalogFileCount = $catalogFiles.Count
        CatalogBytes = [uint64](($catalogFiles | Measure-Object Length -Sum).Sum)
        CatalogDatabaseFileCount = $catalogDatabaseFiles.Count
        SignatureToolRelativePath = Get-SystemRelativePath -Path $signatureTool
        SignatureToolSha256 = (Get-FileHash -LiteralPath $signatureTool -Algorithm SHA256).Hash
        CriticalChecks = @($criticalChecks)
        CriticalCheckCount = @($criticalChecks).Count
        FileCryptCatalogRelativePath = Get-SystemRelativePath -Path $catalogPathFull
        FileCryptCatalogSha256 = (Get-FileHash -LiteralPath $catalogPathFull -Algorithm SHA256).Hash
    }
    Write-ReplicaLog PASS "Kernel catalog trust gate passed: $($evidence.CatalogFileCount) catalog file(s), $($evidence.CatalogDatabaseFileCount) database file(s), and $($evidence.CriticalCheckCount) critical boot/signature files verified under kernel policy."
    return $evidence
}

function Assert-NoActiveServicingCaptureConflict {
    $conflicts = @(Get-Process -ErrorAction SilentlyContinue | Where-Object {
        $_.Name -in @('dism', 'sfc', 'wbadmin')
    } | Select-Object Name, Id)
    if ($conflicts.Count -gt 0) {
        $description = @($conflicts | ForEach-Object { "$($_.Name)[$($_.Id)]" }) -join ', '
        throw "Refusing a point-in-time Windows/Codex capture while servicing or backup clients are active: $description"
    }
    Write-ReplicaLog PASS 'No DISM, SFC, or Windows Backup client is active at the capture boundary.'
}

function Get-HostCodexBaseline {
    param(
        [string]$ExpectedSessionId,
        [string]$ExpectedTaskTitle
    )

    if ([Environment]::UserName -ne 'Admin') {
        throw "This replica workflow is validated for the Admin profile; current user is $([Environment]::UserName)."
    }

    $package = Get-AppxPackage -Name 'OpenAI.Codex' -ErrorAction Stop | Select-Object -First 1
    if ($null -eq $package) { throw 'The OpenAI.Codex desktop package is not registered for Admin.' }
    $manifestPath = Join-Path $package.InstallLocation 'AppxManifest.xml'
    $desktopExe = Join-Path $package.InstallLocation 'app\ChatGPT.exe'
    if (-not (Test-Path -LiteralPath $manifestPath -PathType Leaf)) { throw 'The Codex AppxManifest.xml is missing.' }
    if (-not (Test-Path -LiteralPath $desktopExe -PathType Leaf)) { throw 'The Codex desktop executable is missing.' }

    $codexHome = Join-Path $env:USERPROFILE '.codex'
    $authPath = Join-Path $codexHome 'auth.json'
    $configPath = Join-Path $codexHome 'config.toml'
    if (-not (Test-Path -LiteralPath $authPath -PathType Leaf) -or (Get-Item -LiteralPath $authPath).Length -eq 0) {
        throw 'The file-backed Codex authentication cache is missing or empty.'
    }
    if (-not (Test-Path -LiteralPath $configPath -PathType Leaf)) { throw 'Codex config.toml is missing.' }

    $cli = Get-ChildItem -LiteralPath (Join-Path $env:LOCALAPPDATA 'OpenAI\Codex\bin') -Filter 'codex.exe' -File -Recurse -ErrorAction Stop |
        Sort-Object LastWriteTimeUtc -Descending | Select-Object -First 1
    if ($null -eq $cli) { throw 'The Codex CLI shipped with the desktop application is missing.' }
    $savedErrorActionPreference = $ErrorActionPreference
    try {
        $ErrorActionPreference = 'Continue'
        $loginOutput = @(& $cli.FullName login status 2>&1)
        $loginExitCode = $LASTEXITCODE
    }
    finally { $ErrorActionPreference = $savedErrorActionPreference }
    $loginStatus = ($loginOutput -join ' ').Trim()
    if ($loginExitCode -ne 0 -or $loginStatus -notmatch '^Logged in using ChatGPT') {
        throw "Codex login cache is not ready: $loginStatus"
    }

    $winlogon = Get-ItemProperty -LiteralPath 'Registry::HKEY_LOCAL_MACHINE\SOFTWARE\Microsoft\Windows NT\CurrentVersion\Winlogon'
    $lsaSecretPresent = Test-Path -LiteralPath 'Registry::HKEY_LOCAL_MACHINE\SECURITY\Policy\Secrets\DefaultPassword'
    [bool]$lsaSecretRetrieved = $false
    [int]$lsaError = 0
    [int]$logonError = 0
    $autoLogonCredentialValid = [ReplicaNativeMethods]::ValidateAutoLogonCredential(
        [Environment]::UserName,
        $env:COMPUTERNAME,
        [ref]$lsaSecretRetrieved,
        [ref]$lsaError,
        [ref]$logonError
    )
    if ([string]$winlogon.AutoAdminLogon -ne '1' -or [string]$winlogon.DefaultUserName -ne [Environment]::UserName -or -not $lsaSecretPresent -or -not $lsaSecretRetrieved -or -not $autoLogonCredentialValid) {
        throw "Automatic Admin logon is not usable for zero-touch guest validation (LSA=$lsaError, LogonUser=$logonError)."
    }

    $userPackageKey = "Registry::HKEY_CURRENT_USER\Software\Classes\Local Settings\Software\Microsoft\Windows\CurrentVersion\AppModel\Repository\Packages\$($package.PackageFullName)"
    if (-not (Test-Path -LiteralPath $userPackageKey)) {
        throw 'The Codex desktop package registration is absent from the Admin user registry.'
    }

    $packageData = Join-Path $env:LOCALAPPDATA "Packages\$($package.PackageFamilyName)"
    $storeDefinitions = @(
        [pscustomobject]@{ Name = 'CodexHome'; Path = $codexHome; Immutable = $false },
        [pscustomobject]@{ Name = 'LocalOpenAI'; Path = (Join-Path $env:LOCALAPPDATA 'OpenAI'); Immutable = $false },
        [pscustomobject]@{ Name = 'PackageData'; Path = $packageData; Immutable = $false },
        [pscustomobject]@{ Name = 'InstalledPackage'; Path = $package.InstallLocation; Immutable = $true }
    )
    $stores = foreach ($definition in $storeDefinitions) {
        $evidence = Get-DirectoryFileEvidence -Path $definition.Path
        if ($evidence.FileCount -eq 0 -or $evidence.Bytes -eq 0) { throw "Codex store is empty: $($definition.Path)" }
        [pscustomobject]@{
            Name = $definition.Name
            RelativePath = Get-SystemRelativePath -Path $definition.Path
            FileCount = $evidence.FileCount
            Bytes = $evidence.Bytes
            NewestWriteUtc = $evidence.NewestWriteUtc
            Immutable = $definition.Immutable
        }
    }

    $sessionRoots = @(
        (Join-Path $codexHome 'sessions'),
        (Join-Path $codexHome 'archived_sessions')
    )
    $sessionFiles = @($sessionRoots | ForEach-Object {
        Get-ChildItem -LiteralPath $_ -Filter '*.jsonl' -File -Recurse -ErrorAction Stop
    })
    if ($sessionFiles.Count -eq 0) { throw 'No Codex session files were found.' }
    $sessionInventory = @($sessionFiles | ForEach-Object {
        [pscustomobject]@{
            RelativePath = Get-SystemRelativePath -Path $_.FullName
            Length = [uint64]$_.Length
            LastWriteUtc = $_.LastWriteTimeUtc.ToString('o')
        }
    })

    $expectedSession = if ([string]::IsNullOrWhiteSpace($ExpectedSessionId)) {
        $sessionFiles | Sort-Object LastWriteTimeUtc -Descending | Select-Object -First 1
    }
    else {
        $sessionFiles | Where-Object { $_.Name -like "*$ExpectedSessionId*" } | Select-Object -First 1
    }
    if ($null -eq $expectedSession) { throw "Expected Codex session was not found: $ExpectedSessionId" }

    $databaseFiles = @(Get-ChildItem -LiteralPath $codexHome -Force -File -Recurse -ErrorAction Stop |
        Where-Object { $_.Extension -in @('.sqlite', '.db') })
    if ($databaseFiles.Count -eq 0) { throw 'No Codex SQLite state databases were found.' }
    foreach ($databaseFile in $databaseFiles) {
        if (-not (Test-SqliteHeader -Path $databaseFile.FullName)) {
            throw "Host Codex SQLite database has an invalid header: $($databaseFile.FullName)"
        }
    }
    $userSid = [Security.Principal.WindowsIdentity]::GetCurrent().User.Value
    $dpapiProtectPath = Join-Path $env:APPDATA "Microsoft\Protect\$userSid"
    if (-not (Test-Path -LiteralPath $dpapiProtectPath -PathType Container) -or @(Get-ChildItem -LiteralPath $dpapiProtectPath -Force -File -Recurse).Count -eq 0) {
        throw 'The Admin DPAPI master-key store is missing or empty.'
    }

    $kernelCatalogTrust = Get-KernelCatalogTrustEvidence
    $baseline = [pscustomobject]@{
        UserName = [Environment]::UserName
        UserSid = $userSid
        PackageName = $package.Name
        PackageVersion = [string]$package.Version
        PackageFullName = $package.PackageFullName
        PackageFamilyName = $package.PackageFamilyName
        AppUserModelId = "$($package.PackageFamilyName)!App"
        ManifestRelativePath = Get-SystemRelativePath -Path $manifestPath
        ManifestSha256 = (Get-FileHash -LiteralPath $manifestPath -Algorithm SHA256).Hash
        DesktopExeRelativePath = Get-SystemRelativePath -Path $desktopExe
        DesktopExeSha256 = (Get-FileHash -LiteralPath $desktopExe -Algorithm SHA256).Hash
        CodexCliRelativePath = Get-SystemRelativePath -Path $cli.FullName
        CodexCliSha256 = (Get-FileHash -LiteralPath $cli.FullName -Algorithm SHA256).Hash
        AuthRelativePath = Get-SystemRelativePath -Path $authPath
        AuthBytes = [uint64](Get-Item -LiteralPath $authPath).Length
        AuthSha256 = (Get-FileHash -LiteralPath $authPath -Algorithm SHA256).Hash
        ConfigRelativePath = Get-SystemRelativePath -Path $configPath
        LoginStatus = $loginStatus
        AutoAdminLogon = $true
        LsaDefaultPasswordSecretPresent = $true
        AutoLogonCredentialValidated = $true
        UserPackageRegistrationPresent = $true
        Stores = @($stores)
        Sessions = $sessionInventory
        SessionCount = $sessionInventory.Count
        ExpectedSessionId = $ExpectedSessionId
        ExpectedTaskTitle = $ExpectedTaskTitle
        ExpectedSessionRelativePath = Get-SystemRelativePath -Path $expectedSession.FullName
        ExpectedSessionMinimumBytes = [uint64]$expectedSession.Length
        DatabaseRelativePaths = @($databaseFiles | ForEach-Object { Get-SystemRelativePath -Path $_.FullName })
        KernelCatalogTrust = $kernelCatalogTrust
        CapturedAfterUtcFloor = (Get-Date).ToUniversalTime().ToString('o')
    }
    Write-ReplicaLog PASS "Host Codex baseline passed: package $($baseline.PackageVersion), $($baseline.SessionCount) session file(s), file-backed ChatGPT login, registered desktop app, and protected zero-touch Admin logon."
    return $baseline
}

function Test-SqliteHeader {
    param([string]$Path)

    $stream = [IO.File]::Open($Path, [IO.FileMode]::Open, [IO.FileAccess]::Read, [IO.FileShare]::ReadWrite)
    try {
        $header = New-Object byte[] 16
        if ($stream.Read($header, 0, $header.Length) -ne 16) { return $false }
        return [Text.Encoding]::ASCII.GetString($header) -eq "SQLite format 3$([char]0)"
    }
    finally { $stream.Dispose() }
}

function Test-OfflineCodexState {
    param(
        [string]$WindowsRoot,
        [object]$Baseline
    )

    $storeResults = foreach ($store in $Baseline.Stores) {
        $capturedPath = Join-Path $WindowsRoot $store.RelativePath
        $captured = Get-DirectoryFileEvidence -Path $capturedPath
        if ($store.Immutable) {
            if ($captured.FileCount -ne $store.FileCount -or $captured.Bytes -ne $store.Bytes) {
                throw "Immutable Codex package inventory changed in the VSS image: $($store.Name)."
            }
        }
        elseif (-not $ReuseLatestBackup) {
            $minimumFiles = [int][math]::Floor([double]$store.FileCount * 0.95)
            $minimumBytes = [uint64][math]::Floor([double]$store.Bytes * 0.80)
            if ($captured.FileCount -lt $minimumFiles -or $captured.Bytes -lt $minimumBytes) {
                throw "Codex store inventory is materially incomplete in the VSS image: $($store.Name)."
            }
        }
        elseif ($captured.FileCount -eq 0 -or $captured.Bytes -eq 0) {
            throw "Codex store is empty in the reused VSS image: $($store.Name)."
        }
        [pscustomobject]@{ Name = $store.Name; RelativePath = $store.RelativePath; FileCount = $captured.FileCount; Bytes = $captured.Bytes }
    }

    $capturedSessionRoots = @(
        (Join-Path $WindowsRoot 'Users\Admin\.codex\sessions'),
        (Join-Path $WindowsRoot 'Users\Admin\.codex\archived_sessions')
    )
    $capturedSessionsByName = @{}
    foreach ($capturedSessionFile in @($capturedSessionRoots | ForEach-Object {
        Get-ChildItem -LiteralPath $_ -Filter '*.jsonl' -File -Recurse -ErrorAction Stop
    })) {
        $capturedSessionsByName[$capturedSessionFile.Name] = $capturedSessionFile.FullName
    }
    foreach ($session in $Baseline.Sessions) {
        $capturedSession = Join-Path $WindowsRoot $session.RelativePath
        if (-not (Test-Path -LiteralPath $capturedSession -PathType Leaf)) {
            $sessionName = Split-Path -Leaf $session.RelativePath
            if (-not $capturedSessionsByName.ContainsKey($sessionName)) {
                throw "A pre-capture Codex session is absent from the VSS image: $($session.RelativePath)"
            }
            $capturedSession = [string]$capturedSessionsByName[$sessionName]
        }
        if (-not $ReuseLatestBackup -and [uint64](Get-Item -LiteralPath $capturedSession).Length -lt [uint64]$session.Length) {
            throw "A Codex session is truncated in the VSS image: $($session.RelativePath)"
        }
    }

    $expectedSessionPath = Join-Path $WindowsRoot $Baseline.ExpectedSessionRelativePath
    if (-not (Test-Path -LiteralPath $expectedSessionPath -PathType Leaf)) {
        $expectedSessionName = Split-Path -Leaf $Baseline.ExpectedSessionRelativePath
        if (-not $capturedSessionsByName.ContainsKey($expectedSessionName)) { throw 'The expected current Codex session is absent from the VSS image.' }
        $expectedSessionPath = [string]$capturedSessionsByName[$expectedSessionName]
    }
    if (-not $ReuseLatestBackup -and [uint64](Get-Item -LiteralPath $expectedSessionPath).Length -lt [uint64]$Baseline.ExpectedSessionMinimumBytes) {
        throw 'The expected current Codex session is not complete through the pre-capture byte floor.'
    }

    $hashChecks = @(
        [pscustomobject]@{ Name = 'auth.json'; RelativePath = $Baseline.AuthRelativePath; Expected = $Baseline.AuthSha256 },
        [pscustomobject]@{ Name = 'AppxManifest.xml'; RelativePath = $Baseline.ManifestRelativePath; Expected = $Baseline.ManifestSha256 },
        [pscustomobject]@{ Name = 'ChatGPT.exe'; RelativePath = $Baseline.DesktopExeRelativePath; Expected = $Baseline.DesktopExeSha256 },
        [pscustomobject]@{ Name = 'codex.exe'; RelativePath = $Baseline.CodexCliRelativePath; Expected = $Baseline.CodexCliSha256 }
    )
    foreach ($check in $hashChecks) {
        $capturedPath = Join-Path $WindowsRoot $check.RelativePath
        if (-not (Test-Path -LiteralPath $capturedPath -PathType Leaf)) { throw "Captured $($check.Name) is missing." }
        if ((Get-FileHash -LiteralPath $capturedPath -Algorithm SHA256).Hash -ne $check.Expected) {
            throw "Captured $($check.Name) does not match the source hash."
        }
    }

    $catalogTrust = $Baseline.KernelCatalogTrust
    if ($null -eq $catalogTrust) { throw 'The source kernel-catalog trust baseline is absent.' }
    $capturedCatalogRoot = Join-Path $WindowsRoot "Windows\System32\CatRoot\$($catalogTrust.CatalogSetId)"
    $capturedCatalogDatabaseRoot = Join-Path $WindowsRoot "Windows\System32\CatRoot2\$($catalogTrust.CatalogSetId)"
    $capturedCatalogFiles = @(Get-ChildItem -LiteralPath $capturedCatalogRoot -Filter '*.cat' -File -ErrorAction Stop)
    $capturedCatalogDatabaseFiles = @(Get-ChildItem -LiteralPath $capturedCatalogDatabaseRoot -File -Recurse -ErrorAction Stop)
    if ($capturedCatalogFiles.Count -lt [int]$catalogTrust.CatalogFileCount) {
        throw "The VSS image contains only $($capturedCatalogFiles.Count) kernel catalog files; the source baseline had $($catalogTrust.CatalogFileCount)."
    }
    if ($capturedCatalogDatabaseFiles.Count -eq 0) {
        throw 'The VSS image has no kernel catalog database files.'
    }

    $capturedSignatureTool = Join-Path $WindowsRoot $catalogTrust.SignatureToolRelativePath
    if (-not (Test-Path -LiteralPath $capturedSignatureTool -PathType Leaf) -or
        (Get-FileHash -LiteralPath $capturedSignatureTool -Algorithm SHA256).Hash -ne $catalogTrust.SignatureToolSha256) {
        throw 'The VSS image does not contain the exact Microsoft signature verifier used by the source gate.'
    }
    $capturedFileCryptCatalog = Join-Path $WindowsRoot $catalogTrust.FileCryptCatalogRelativePath
    if (-not (Test-Path -LiteralPath $capturedFileCryptCatalog -PathType Leaf) -or
        (Get-FileHash -LiteralPath $capturedFileCryptCatalog -Algorithm SHA256).Hash -ne $catalogTrust.FileCryptCatalogSha256) {
        throw 'The VSS image does not contain the exact installed catalog selected for filecrypt.sys.'
    }
    foreach ($criticalCheck in $catalogTrust.CriticalChecks) {
        $capturedCriticalPath = Join-Path $WindowsRoot $criticalCheck.RelativePath
        if (-not (Test-Path -LiteralPath $capturedCriticalPath -PathType Leaf) -or
            (Get-FileHash -LiteralPath $capturedCriticalPath -Algorithm SHA256).Hash -ne $criticalCheck.Sha256) {
            throw "The VSS image changed or omitted a kernel-critical file: $($criticalCheck.RelativePath)"
        }
    }
    $backupTargetVhdExclusionVerified = $null
    $backupTargetVhdProperty = $Baseline.PSObject.Properties['BackupTargetVhdRelativePath']
    if ($null -ne $backupTargetVhdProperty -and -not [string]::IsNullOrWhiteSpace([string]$backupTargetVhdProperty.Value)) {
        $capturedBackingVhd = Join-Path $WindowsRoot ([string]$backupTargetVhdProperty.Value)
        $maximumProperty = $Baseline.PSObject.Properties['BackupTargetVhdMaximumCapturedShellBytes']
        if ($null -eq $maximumProperty -or [uint64]$maximumProperty.Value -lt 1MB) {
            throw 'The mounted backup-target VHDX has no safe captured-shell ceiling.'
        }
        $capturedShellBytes = [uint64]0
        if (Test-Path -LiteralPath $capturedBackingVhd -PathType Leaf) {
            $capturedShellBytes = [uint64](Get-Item -LiteralPath $capturedBackingVhd).Length
            if ($capturedShellBytes -gt [uint64]$maximumProperty.Value) {
                throw "The mounted backup-target VHDX captured $capturedShellBytes bytes, exceeding the non-recursive shell ceiling $($maximumProperty.Value)."
            }
        }
        $backupTargetVhdExclusionVerified = [pscustomobject]@{
            Verified = $true
            CapturedShellBytes = $capturedShellBytes
            MaximumAllowedBytes = [uint64]$maximumProperty.Value
            CapturedShellWithinNonRecursiveCeiling = $true
            RemovalDeferredToWritableVerifierInjection = ($capturedShellBytes -gt 0)
        }
    }

    $capturedDatabasePaths = if ($ReuseLatestBackup) {
        @(Get-ChildItem -LiteralPath (Join-Path $WindowsRoot 'Users\Admin\.codex') -Force -File -Recurse -ErrorAction Stop |
            Where-Object { $_.Extension -in @('.sqlite', '.db') } | Select-Object -ExpandProperty FullName)
    }
    else {
        @($Baseline.DatabaseRelativePaths | ForEach-Object { Join-Path $WindowsRoot $_ })
    }
    if ($capturedDatabasePaths.Count -eq 0) { throw 'The VSS image has no Codex SQLite state databases.' }
    foreach ($databasePath in $capturedDatabasePaths) {
        if (-not (Test-Path -LiteralPath $databasePath -PathType Leaf) -or -not (Test-SqliteHeader -Path $databasePath)) {
            throw "Captured Codex SQLite database has an invalid header: $databasePath"
        }
    }

    $identityPaths = @(
        'Windows\System32\config\SAM',
        'Windows\System32\config\SECURITY',
        'Users\Admin\NTUSER.DAT',
        "Users\Admin\AppData\Roaming\Microsoft\Protect\$($Baseline.UserSid)"
    )
    $missingIdentityPaths = @($identityPaths | Where-Object { -not (Test-Path -LiteralPath (Join-Path $WindowsRoot $_)) })
    if ($missingIdentityPaths.Count -gt 0) {
        throw "Credential/identity material is incomplete in the VSS image: $($missingIdentityPaths -join ', ')."
    }

    Write-ReplicaLog PASS "Codex offline fidelity gates passed: all $($Baseline.SessionCount) pre-capture sessions, current task byte floor, authentication cache, app/CLI binaries, package payload, SQLite state, user registry, DPAPI, SAM, LSA security hive, kernel catalog database, and $(@($catalogTrust.CriticalChecks).Count) kernel-critical files are present."
    return [pscustomobject]@{
        PackageVersion = $Baseline.PackageVersion
        SessionCount = $Baseline.SessionCount
        ExpectedSessionRelativePath = $expectedSessionPath.Substring($WindowsRoot.Length)
        ExpectedSessionCapturedBytes = [uint64](Get-Item -LiteralPath $expectedSessionPath).Length
        Stores = @($storeResults)
        AuthSha256 = $Baseline.AuthSha256
        ManifestSha256 = $Baseline.ManifestSha256
        DesktopExeSha256 = $Baseline.DesktopExeSha256
        CodexCliSha256 = $Baseline.CodexCliSha256
        DatabaseCount = $capturedDatabasePaths.Count
        IdentityMaterialPresent = $true
        KernelCatalogTrust = [pscustomobject]@{
            CatalogFileCount = $capturedCatalogFiles.Count
            CatalogDatabaseFileCount = $capturedCatalogDatabaseFiles.Count
            CriticalFilesHashMatched = @($catalogTrust.CriticalChecks).Count
            FileCryptCatalogSha256 = $catalogTrust.FileCryptCatalogSha256
            SignatureToolSha256 = $catalogTrust.SignatureToolSha256
        }
        BackupTargetVhdExclusionVerified = $backupTargetVhdExclusionVerified
    }
}

function Add-TemporaryAccessPath {
    param(
        [int]$DiskNumber,
        [int]$PartitionNumber
    )

    $partition = Get-Partition -DiskNumber $DiskNumber -PartitionNumber $PartitionNumber
    $existing = @($partition.AccessPaths | Where-Object { $_ -match '^[A-Z]:\\$' } | Select-Object -First 1)
    if ($existing.Count -eq 1) {
        return [pscustomobject]@{ Root = $existing[0]; Added = $false }
    }

    $letter = Get-FreeDriveLetter
    $root = "${letter}:\"
    Add-PartitionAccessPath -DiskNumber $DiskNumber -PartitionNumber $PartitionNumber -AccessPath $root
    return [pscustomobject]@{ Root = $root; Added = $true }
}

function Get-BackupVhdRole {
    param([string]$Path)

    $mounted = $false
    $accesses = [System.Collections.Generic.List[object]]::new()
    try {
        $disk = Mount-VHD -Path $Path -ReadOnly -Passthru
        $mounted = $true
        $partitions = @(Get-Partition -DiskNumber $disk.DiskNumber | Where-Object { $_.GptType -ne $msrGptType })
        foreach ($partition in $partitions) {
            $access = Add-TemporaryAccessPath -DiskNumber $disk.DiskNumber -PartitionNumber $partition.PartitionNumber
            $accesses.Add([pscustomobject]@{ Partition = $partition; Access = $access })
            if (Test-Path -LiteralPath (Join-Path $access.Root 'Windows\System32\config\SYSTEM')) {
                return 'Windows'
            }
            if (Test-Path -LiteralPath (Join-Path $access.Root 'EFI\Microsoft\Boot\bootmgfw.efi')) {
                return 'EFI'
            }
            if (
                (Test-Path -LiteralPath (Join-Path $access.Root 'Recovery')) -or
                (Test-Path -LiteralPath (Join-Path $access.Root 'Windows\System32\Recovery'))
            ) {
                return 'Recovery'
            }
        }
        return 'Unknown'
    }
    finally {
        foreach ($item in $accesses) {
            if ($item.Access.Added) {
                Remove-PartitionAccessPath -DiskNumber $disk.DiskNumber -PartitionNumber $item.Partition.PartitionNumber -AccessPath $item.Access.Root -ErrorAction SilentlyContinue
            }
        }
        if ($mounted) { Dismount-VHD -Path $Path -ErrorAction SilentlyContinue }
    }
}

function Get-LatestBackupSet {
    param([string]$BackupRoot)

    $machineRoot = Join-Path $BackupRoot $env:COMPUTERNAME
    if (-not (Test-Path -LiteralPath $machineRoot -PathType Container)) {
        throw "Windows Backup machine directory was not found: $machineRoot"
    }
    $backupSet = Get-ChildItem -LiteralPath $machineRoot -Directory |
        Where-Object Name -like 'Backup *' |
        Sort-Object LastWriteTime -Descending |
        Select-Object -First 1
    if ($null -eq $backupSet) {
        throw "No Backup directory exists under $machineRoot."
    }

    $records = [System.Collections.Generic.List[object]]::new()
    foreach ($file in Get-ChildItem -LiteralPath $backupSet.FullName -Filter '*.vhdx' -File) {
        $vhd = Get-VHD -Path $file.FullName
        $records.Add([pscustomobject]@{
            Role = Get-BackupVhdRole -Path $file.FullName
            Path = $file.FullName
            Length = $file.Length
            VirtualSize = $vhd.Size
            FileSize = $vhd.FileSize
        })
    }
    if (@($records | Where-Object Role -eq 'Recovery').Count -eq 0) {
        $unknown = @($records | Where-Object Role -eq 'Unknown')
        if ($unknown.Count -eq 1) {
            $unknown[0].Role = 'Recovery'
        }
    }
    foreach ($requiredRole in @('Windows', 'EFI', 'Recovery')) {
        if (@($records | Where-Object Role -eq $requiredRole).Count -ne 1) {
            throw "Expected exactly one $requiredRole VHDX in $($backupSet.FullName)."
        }
    }
    Write-ReplicaLog PASS "Validated latest Windows Backup set $($backupSet.FullName)."
    return [pscustomobject]@{ Root = $BackupRoot; Directory = $backupSet.FullName; Volumes = @($records) }
}

function Get-ProtectedBackupRetentionEvidence {
    param(
        [object]$Backup,
        [string]$ArchiveParent,
        [object]$Expected
    )

    $archiveParentFull = [IO.Path]::GetFullPath($ArchiveParent).TrimEnd('\')
    $backupRootFull = [IO.Path]::GetFullPath([string]$Backup.Root).TrimEnd('\')
    $backupDirectoryFull = [IO.Path]::GetFullPath([string]$Backup.Directory).TrimEnd('\')
    if (-not $backupRootFull.StartsWith("${archiveParentFull}\", [StringComparison]::OrdinalIgnoreCase)) {
        throw "Protected Windows Backup is outside its dedicated archive parent: $backupRootFull"
    }
    if (-not (Test-Path -LiteralPath $backupRootFull -PathType Container) -or
        -not (Test-Path -LiteralPath $backupDirectoryFull -PathType Container)) {
        throw "Protected Windows Backup root/set is missing: $backupRootFull"
    }
    if (-not $backupDirectoryFull.StartsWith("${backupRootFull}\", [StringComparison]::OrdinalIgnoreCase)) {
        throw "Windows Backup set is outside its protected root: $backupDirectoryFull"
    }

    $allFiles = @(Get-ChildItem -LiteralPath $backupRootFull -File -Recurse -Force -ErrorAction Stop)
    if ($allFiles.Count -eq 0) { throw "Protected Windows Backup is empty: $backupRootFull" }
    $volumeEvidence = foreach ($volume in $Backup.Volumes) {
        $volumePath = [IO.Path]::GetFullPath([string]$volume.Path)
        if (-not $volumePath.StartsWith("${backupRootFull}\", [StringComparison]::OrdinalIgnoreCase) -or
            -not (Test-Path -LiteralPath $volumePath -PathType Leaf)) {
            throw "A protected Windows Backup VHDX is missing or outside the archive: $volumePath"
        }
        $item = Get-Item -LiteralPath $volumePath -Force
        if ([uint64]$item.Length -ne [uint64]$volume.Length) {
            throw "A protected Windows Backup VHDX changed length: $volumePath"
        }
        [pscustomobject]@{
            Role = [string]$volume.Role
            RelativePath = $volumePath.Substring($backupRootFull.Length).TrimStart('\')
            Length = [uint64]$item.Length
            LastWriteUtc = $item.LastWriteTimeUtc.ToString('o')
        }
    }
    $metadataEvidence = @($allFiles | Where-Object Extension -ne '.vhdx' | ForEach-Object {
        [pscustomobject]@{
            RelativePath = $_.FullName.Substring($backupRootFull.Length).TrimStart('\')
            Length = [uint64]$_.Length
            LastWriteUtc = $_.LastWriteTimeUtc.ToString('o')
            Sha256 = (Get-FileHash -LiteralPath $_.FullName -Algorithm SHA256).Hash
        }
    })

    $evidence = [pscustomobject]@{
        VerifiedUtc = (Get-Date).ToUniversalTime().ToString('o')
        Root = $backupRootFull
        Directory = $backupDirectoryFull
        FileCount = $allFiles.Count
        Bytes = [uint64](($allFiles | Measure-Object Length -Sum).Sum)
        Volumes = @($volumeEvidence)
        MetadataFiles = $metadataEvidence
    }

    if ($null -ne $Expected) {
        if (
            -not $evidence.Root.Equals([string]$Expected.Root, [StringComparison]::OrdinalIgnoreCase) -or
            -not $evidence.Directory.Equals([string]$Expected.Directory, [StringComparison]::OrdinalIgnoreCase) -or
            [int]$evidence.FileCount -ne [int]$Expected.FileCount -or
            [uint64]$evidence.Bytes -ne [uint64]$Expected.Bytes -or
            @($evidence.Volumes).Count -ne @($Expected.Volumes).Count -or
            @($evidence.MetadataFiles).Count -ne @($Expected.MetadataFiles).Count
        ) {
            throw 'Protected Windows Backup inventory changed after the pre-launch retention gate.'
        }
        foreach ($currentVolume in $evidence.Volumes) {
            $prior = @($Expected.Volumes | Where-Object Role -eq $currentVolume.Role)
            if ($prior.Count -ne 1 -or
                [string]$prior[0].RelativePath -ne [string]$currentVolume.RelativePath -or
                [uint64]$prior[0].Length -ne [uint64]$currentVolume.Length -or
                [string]$prior[0].LastWriteUtc -ne [string]$currentVolume.LastWriteUtc) {
                throw "Protected Windows Backup volume changed after construction: $($currentVolume.Role)"
            }
        }
        foreach ($currentMetadata in $evidence.MetadataFiles) {
            $prior = @($Expected.MetadataFiles | Where-Object RelativePath -eq $currentMetadata.RelativePath)
            if ($prior.Count -ne 1 -or
                [uint64]$prior[0].Length -ne [uint64]$currentMetadata.Length -or
                [string]$prior[0].LastWriteUtc -ne [string]$currentMetadata.LastWriteUtc -or
                [string]$prior[0].Sha256 -ne [string]$currentMetadata.Sha256) {
                throw "Protected Windows Backup metadata changed after construction: $($currentMetadata.RelativePath)"
            }
        }
    }

    Write-ReplicaLog PASS "Protected backup retention gate passed: $($evidence.FileCount) file(s), $($evidence.Volumes.Count) required VHDX volume(s), and $($evidence.MetadataFiles.Count) hashed metadata file(s) remain intact beneath $backupRootFull."
    return $evidence
}

function Remove-VerifiedFailedWindowsBackupRoot {
    param([string]$Path)

    if ([string]::IsNullOrWhiteSpace($Path)) { return }
    if (Get-Process -Name 'wbadmin' -ErrorAction SilentlyContinue) {
        throw 'Refusing failed-backup cleanup while a wbadmin client is active.'
    }
    $fullPath = [IO.Path]::GetFullPath($Path).TrimEnd('\')
    $driveRoot = [IO.Path]::GetPathRoot($fullPath)
    $onlyAllowedPath = [IO.Path]::GetFullPath((Join-Path $driveRoot 'WindowsImageBackup')).TrimEnd('\')
    if (-not $fullPath.Equals($onlyAllowedPath, [StringComparison]::OrdinalIgnoreCase) -or
        $driveRoot.TrimEnd('\').Equals($env:SystemDrive, [StringComparison]::OrdinalIgnoreCase)) {
        throw "Failed-backup cleanup is restricted to an exact non-system-drive WindowsImageBackup root: $fullPath"
    }
    if (-not (Test-Path -LiteralPath $fullPath -PathType Container)) {
        throw "Requested failed-backup root does not exist: $fullPath"
    }
    $rootItem = Get-Item -LiteralPath $fullPath -Force
    if (($rootItem.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0) {
        throw "Failed-backup root is a reparse point and will not be removed: $fullPath"
    }
    if ($rootItem.CreationTimeUtc -lt (Get-Date).ToUniversalTime().AddHours(-8)) {
        throw "Failed-backup root is older than this recovery window and will not be removed: $fullPath"
    }
    $machineDirectories = @(Get-ChildItem -LiteralPath $fullPath -Directory -Force -ErrorAction Stop)
    if ($machineDirectories.Count -ne 1 -or $machineDirectories[0].Name -ne $env:COMPUTERNAME) {
        throw 'Failed-backup root does not contain exactly the current machine directory.'
    }
    $errorLogs = @(Get-ChildItem -LiteralPath $fullPath -Filter 'Backup_Error-*.log' -File -Recurse -Force -ErrorAction Stop)
    if ($errorLogs.Count -eq 0) { throw 'Failed-backup root has no Windows Backup failure log.' }
    $errorText = @($errorLogs | ForEach-Object { Get-Content -LiteralPath $_.FullName -Raw -ErrorAction Stop }) -join [Environment]::NewLine
    $targetDriveLetter = $driveRoot.TrimEnd('\').TrimEnd(':')
    $targetFreeBytes = [uint64](Get-Volume -DriveLetter $targetDriveLetter -ErrorAction Stop).SizeRemaining
    $explicitCapacityError = $errorText -match '(?i)not enough space|0x80070070'
    $targetWriteFailure = $errorText -match '(?i)error when writing data to the backup target'
    if (-not $explicitCapacityError -and -not $targetWriteFailure) {
        throw 'Failed-backup root does not prove the expected target-capacity failure.'
    }
    $validatedBackupExists = $false
    try {
        [void](Get-LatestBackupSet -BackupRoot $fullPath)
        $validatedBackupExists = $true
    }
    catch { }
    if ($validatedBackupExists) {
        throw 'The requested cleanup root contains a structurally complete Windows Backup and will not be removed.'
    }
    $failedFiles = @(Get-ChildItem -LiteralPath $fullPath -File -Recurse -Force -ErrorAction Stop)
    $failedBytes = [uint64](($failedFiles | Measure-Object Length -Sum).Sum)
    Remove-Item -LiteralPath $fullPath -Recurse -Force -ErrorAction Stop
    if (Test-Path -LiteralPath $fullPath) { throw "Failed to remove exact incomplete backup root: $fullPath" }
    Write-ReplicaLog PASS ("Removed only the verified current insufficient-space Windows Backup artifact at {0} ({1:N2} GiB logical)." -f $fullPath, ($failedBytes / 1GB))
}

function New-IsolatedBackupTargetVhd {
    param(
        [string]$Path,
        [string]$Drive,
        [int]$SizeGB
    )

    $fullPath = [IO.Path]::GetFullPath($Path)
    $allowedParent = [IO.Path]::GetFullPath((Join-Path $env:ProgramData 'Verified-Windows-Replica-Backup-Targets')).TrimEnd('\')
    if (-not $fullPath.StartsWith("${allowedParent}\", [StringComparison]::OrdinalIgnoreCase)) {
        throw "Backup target VHDX must be beneath the dedicated protected path $allowedParent."
    }
    if (-not [IO.Path]::GetPathRoot($fullPath).TrimEnd('\').Equals($env:SystemDrive, [StringComparison]::OrdinalIgnoreCase)) {
        throw 'The isolated backup target VHDX must use the ample NTFS system volume on this host.'
    }
    if (Test-Path -LiteralPath $fullPath) { throw "Backup target VHDX already exists: $fullPath" }
    $driveLetter = $Drive.TrimEnd(':')
    if (Get-Volume -DriveLetter $driveLetter -ErrorAction SilentlyContinue) {
        throw "Backup target staging drive letter is already in use: $Drive"
    }

    $windowsVolume = Get-Volume -DriveLetter $env:SystemDrive.TrimEnd(':')
    $usedWindowsBytes = [uint64]($windowsVolume.Size - $windowsVolume.SizeRemaining)
    $minimumTargetBytes = [uint64]($usedWindowsBytes * 2.25 + 32GB)
    $targetVirtualBytes = [uint64]$SizeGB * [uint64]1GB
    if ($targetVirtualBytes -lt $minimumTargetBytes) {
        throw ("The isolated backup target needs at least {0:N2} GiB virtual capacity; {1:N2} GiB was requested." -f ($minimumTargetBytes / 1GB), ($targetVirtualBytes / 1GB))
    }
    $minimumHostFree = [uint64]($usedWindowsBytes * 3.25 + 96GB)
    if ([uint64]$windowsVolume.SizeRemaining -lt $minimumHostFree) {
        throw ("The host needs at least {0:N2} GiB free for the isolated backup, independent bases, and VM children; {1:N2} GiB is free." -f ($minimumHostFree / 1GB), ($windowsVolume.SizeRemaining / 1GB))
    }

    New-Item -ItemType Directory -Path (Split-Path -Parent $fullPath) -Force | Out-Null
    $created = $false
    $mounted = $false
    try {
        New-VHD -Path $fullPath -Dynamic -SizeBytes $targetVirtualBytes -BlockSizeBytes 32MB | Out-Null
        $created = $true
        $disk = Mount-VHD -Path $fullPath -Passthru -ErrorAction Stop
        $mounted = $true
        Initialize-Disk -Number $disk.DiskNumber -PartitionStyle GPT -PassThru | Out-Null
        $partition = New-Partition -DiskNumber $disk.DiskNumber -UseMaximumSize -DriveLetter $driveLetter
        Format-Volume -Partition $partition -FileSystem NTFS -NewFileSystemLabel 'CodexReplicaBackup' -AllocationUnitSize 4096 -Confirm:$false -Force | Out-Null
        $volume = Get-Volume -DriveLetter $driveLetter
        if ($volume.FileSystem -ne 'NTFS' -or [uint64]$volume.SizeRemaining -lt $minimumTargetBytes) {
            throw 'The isolated backup target did not format with the required NTFS capacity.'
        }
        $vhd = Get-VHD -Path $fullPath
        if (-not $vhd.Attached -or $vhd.VhdType -ne 'Dynamic' -or [uint64]$vhd.Size -ne $targetVirtualBytes) {
            throw 'The isolated backup target VHDX failed its attach/type/size gate.'
        }
        $evidence = [pscustomobject]@{
            Path = $fullPath
            Drive = $Drive
            DiskNumber = $disk.DiskNumber
            VhdType = [string]$vhd.VhdType
            VirtualSize = [uint64]$vhd.Size
            FileSystem = [string]$volume.FileSystem
            Label = [string]$volume.FileSystemLabel
            InitialFreeBytes = [uint64]$volume.SizeRemaining
            BackingFileLengthBeforeBackup = [uint64](Get-Item -LiteralPath $fullPath).Length
            MaximumCapturedShellBytes = [uint64]1GB
            Reused = $false
            BackingFileAutoExcludedFromMountedVhdBackup = $true
        }
        Write-ReplicaLog PASS ("Created and mounted an isolated {0:N0} GiB NTFS backup target at {1}, backed by {2}; Windows Backup excludes mounted VHD backing files from source images." -f ($vhd.Size / 1GB), $Drive, $fullPath)
        return $evidence
    }
    catch {
        if ($mounted) { Dismount-VHD -Path $fullPath -ErrorAction SilentlyContinue }
        if ($created -and (Test-Path -LiteralPath $fullPath)) { Remove-Item -LiteralPath $fullPath -Force -ErrorAction SilentlyContinue }
        throw
    }
}

